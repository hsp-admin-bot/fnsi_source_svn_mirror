  /*
   * 2進数文字列から16進数文字列を取得する.
   */
  private String getHexString(String binString) {
    int dec = Integer.parseInt(binString, 2);
    String hex = Integer.toHexString(dec).toUpperCase();

    return hex;
  }

  /**
   * 左詰め0埋め固定長文字列を返す
   * @param 文字列
   * @param 戻り文字列の長さ
   */
  private String getZeroRightPaddingString(String string, int length) {
    for (int looper = 0; looper < length; looper++) {
      string = "0" + string;
    }
    String rtn = string.substring(string.length() - length, string.length());
    return rtn;
  }

