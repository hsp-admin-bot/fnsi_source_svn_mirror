      int startIdx = i * 2;
      int endIdx = startIdx + 2;

      String hex = "";
      hex = hexString.substring(startIdx, endIdx);
      int dec = Integer.parseInt(hex, 16);
      String bin = Integer.toBinaryString(dec);
      bin = Utilities.getZeroRightPaddingString(bin, 8);

