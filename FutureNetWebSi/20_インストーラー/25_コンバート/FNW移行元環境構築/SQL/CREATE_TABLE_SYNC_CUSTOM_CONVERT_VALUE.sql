-- テーブル削除
-- DROP TABLE SYNC_CUSTOM_CONVERT_VALUE CASCADE CONSTRAINTS;
declare
      num number;
begin
    select count(1) into num from user_tables where table_name = upper('SYNC_CUSTOM_CONVERT_VALUE') ;
    if num > 0 then
        execute immediate 'drop table SYNC_CUSTOM_CONVERT_VALUE CASCADE CONSTRAINTS' ;
    end if;
end;
/
-- テーブル作成
CREATE TABLE SYNC_CUSTOM_CONVERT_VALUE
(
    NTSS_TABLE_NAME VARCHAR2(50),  --NTSSテーブル名
    NTSS_COLUMN_NAME VARCHAR2(50),  --NTSSカラム名
    NTSS_JSON_NAME VARCHAR2(50),  --NTSSJSONキー名
    CONV_VALUE_1 VARCHAR2(4000),  --変換後の値
    CONV_VALUE_2 VARCHAR2(4000),  --変換後の値
    CONV_VALUE_3 VARCHAR2(4000),  --変換後の値
    CONVERSION_TYPE VARCHAR2(30)  --変換種別
)
    tablespace NKK_DATA_COP;
-- コメント追加
COMMENT ON TABLE "SYNC_CUSTOM_CONVERT_VALUE" IS '設定値カスタム変換定義';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."NTSS_TABLE_NAME" IS 'NTSSテーブル名';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."NTSS_COLUMN_NAME" IS 'NTSSカラム名';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."NTSS_JSON_NAME" IS 'NTSSJSONキー名';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."CONV_VALUE_1" IS '変換後の値';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."CONV_VALUE_2" IS '変換後の値';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."CONV_VALUE_3" IS '変換後の値';
COMMENT ON COLUMN "SYNC_CUSTOM_CONVERT_VALUE"."CONVERSION_TYPE" IS '変換種別';
