-- テーブル削除
-- DROP TABLE SYNC_CHECKLIST_HIST CASCADE CONSTRAINTS;
declare
      num number;
begin
    select count(1) into num from user_tables where table_name = upper('SYNC_CHECKLIST_HIST') ;
    if num > 0 then
        execute immediate 'drop table SYNC_CHECKLIST_HIST CASCADE CONSTRAINTS' ;
    end if;
end;
/
-- テーブル作成
