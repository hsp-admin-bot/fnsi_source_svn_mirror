(
	PATID CHAR(12),
	DIALYSIS_NO NUMBER(12,0),
	DIALYSIS_DATE CHAR(8),
	OCCUR_DATE DATE,
	ITEM_NUMBER NUMBER(2,0),
	STAFF_CD CHAR(10),
	CODE CHAR(10),
	LIST_CD CHAR(2),
	LIST_CD_UP_DATE DATE,
	RESULT_NO NUMBER(12,0),	
	KUR_CD CHAR(3),
	BED_NO NUMBER(4,0),
	UP_DATE DATE
