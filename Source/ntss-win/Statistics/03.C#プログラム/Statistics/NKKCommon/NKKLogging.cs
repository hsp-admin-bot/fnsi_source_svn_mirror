            /// <param name="strLogData">ログ内容</param>
            //----------------------------------------------------------------------------------------------------
            public LOG_INFO(String strLogExt, DateTime dtLogDateTime, String strLogData)
            {
                this.strLogExt = strLogExt;
                this.dtLogDateTime = dtLogDateTime;
                this.strLogData = strLogData;
