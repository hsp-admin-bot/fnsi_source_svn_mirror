            //----------------------------------------------------------------------------------------------------
            public void AddLogInfo(String strLogExt, DateTime dtLogDateTime, String strLogData)
            {
                // ログ情報保持キューのロックチェック(10ms待ち)
                if (Monitor.TryEnter(this.m_queLogInfo.SyncRoot, 10))
                {
                    // ロックされていない場合

                    // ロック回避用ログ保持キューのロックチェック
                    lock (this.m_queLogInfoBak.SyncRoot)
                    {
                        // ロック回避用ログ情報保持キューに内容がある場合
                        while (0 < this.m_queLogInfoBak.Count)
                        {
                            // ログ情報保持キューへロック回避用ログ情報保持キューのログ内容を移動
                            this.m_queLogInfo.Enqueue(this.m_queLogInfoBak.Dequeue());
                        }
                    }

                    try
                    {
                        // ログ情報保持キューへログ内容を追加
                        this.m_queLogInfo.Enqueue(new LOG_INFO(strLogExt, dtLogDateTime, strLogData));
                    }
                    finally
                    {
                        // ロック解除
                        Monitor.Exit(this.m_queLogInfo.SyncRoot);
                    }
                }
                else
                {
                    // ロックされている場合

                    // ロック回避用ログ情報保持キューのロック
                    lock (this.m_queLogInfoBak.SyncRoot)
                    {
                        // ログ内容をロック回避用ログ情報保持キューへ追加
                        this.m_queLogInfoBak.Enqueue(new LOG_INFO(strLogExt, dtLogDateTime, strLogData));
                    }
                }

                // スレッドに対してログの書き込み開始を通知
                this.m_LogWriteEvent.Set();
            }
