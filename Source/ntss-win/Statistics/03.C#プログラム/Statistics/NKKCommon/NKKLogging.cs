        /// <summary>
        /// ログファイルを圧縮する
        /// ※当日以外のログファイルは圧縮後に削除する
        /// </summary>
        /// <param name="strServiceName">サービス名</param>
        /// <param name="bLogging">ログ出力フラグ[true：ログ出力あり/false：ログ出力なし]</param>
        /// <returns>true：成功(対象がない場合含む)/false：失敗</returns>
        //----------------------------------------------------------------------------------------------------
        public bool ZipLogFiles(String strServiceName, bool bLogging)
        {
            bool bret = true;
            const String strSearchPattern = "\\d{4}[0-1]\\d[0-3]\\d\\.LOG";

            try
            {
                String strfilename;

                // 正規表現によるファイル名マッチングパターン登録
                Regex reg = new Regex(strSearchPattern, RegexOptions.IgnoreCase);

                // ログファイル格納先に格納されているファイルを全て取得する
                String[] logfiles = System.IO.Directory.GetFiles(this.m_LoggingThread.LogFolder, "*.*", System.IO.SearchOption.TopDirectoryOnly);
                foreach (String strfile in logfiles)
                {
                    try
                    {
                        // ファイル名(+拡張子)のみ取得
                        strfilename = System.IO.Path.GetFileName(strfile);

                        // ファイル名チェック
                        if (reg.Match(strfilename).Success == true)
                        {
                            // 有効なファイル名の場合

                            // 圧縮ファイル名作成
                            String zipfilename = System.IO.Path.ChangeExtension(strfile, "ZIP");

                            // 圧縮済ファイル名チェック
                            if( System.IO.File.Exists( zipfilename ))
                            {
                                // 圧縮済ファイルを削除する
                                System.IO.File.Delete( zipfilename );
                            }

                            // 取得ファイルを圧縮する
                            bool res = TdcLib.TdcLib.CompressZipFile(this.Encoding, zipfilename, strfile, String.Empty, this.ZIP_PASSWORD);

                            // 履歴記録
                            if ( bLogging == true)
                            {
                                this.AddLogInfo(DateTime.Now, strServiceName, LOGGING_CLASS.INFO, String.Format("ログ圧縮{0},{1} → {2}", res ? "成功": "失敗", strfile, zipfilename ));
                            }

                            // 取得ファイルから更新日時を取得する
                            DateTime dtlastwrite = System.IO.File.GetLastWriteTime(strfile);

                            // 本日より前のファイルの場合は削除する
                            if(dtlastwrite < DateTime.Now.Date)
                            {
                                // ファイル削除
                                System.IO.File.Delete(strfile);

                                // 履歴記録
                                if (bLogging == true)
                                {
                                    this.AddLogInfo(DateTime.Now, strServiceName, LOGGING_CLASS.INFO, String.Format("ログ削除,{0}", strfile));
                                }
                            }
                        }
                    }
                    catch (Exception ex)
                    {
#if DEBUG
                        Trace.WriteLine(String.Format("{0}.ZipLogFiles,File:{0},Error:{1}", strfile, ex.ToString()));
#endif
                        // 履歴記録
                        if (bLogging == true)
                        {
                            this.AddLogInfo(DateTime.Now, strServiceName, NKKLogging.LOGGING_CLASS.ERROR,
                                String.Format("{0}.{1},file:{2},error:{3}", this.GetType().Name, MethodBase.GetCurrentMethod().Name, strfile, ex.ToString()));

                        }

                        bret = false;
                    }
                }

            }
            catch (Exception ex)
            {
#if DEBUG
                Trace.WriteLine(String.Format("NKKLogging.ZipLogFiles,StrSearchPattern:{0},Error:{1}", strSearchPattern, ex.ToString()));
#endif
                // 履歴記録
                if (bLogging == true)
                {
                    this.AddLogInfo(DateTime.Now, strServiceName, NKKLogging.LOGGING_CLASS.ERROR,
                        String.Format("{0}.{1},SearchPattern:{2},error:{3}", this.GetType().Name, MethodBase.GetCurrentMethod().Name, strSearchPattern, ex.ToString()));
                }

                bret = false;
            }

            return (bret);
        }
