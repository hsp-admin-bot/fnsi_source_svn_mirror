        /// <summary>
        /// 指定日付以前のログファイルを削除する
        /// </summary>
        /// <param name="strServiceName">サービス名</param>
        /// <param name="nStorageDateCount">ログファイル保持日数[1～]</param>
        /// <param name="bLogging">ログ出力フラグ[true：ログ出力あり/false：ログ出力なし]</param>
        /// <returns>true：成功(対象がない場合含む)/false：失敗</returns>
        //----------------------------------------------------------------------------------------------------
        public bool DeleteLogFiles(String strServiceName, int nStorageDateCount, bool bLogging)
        {
            bool bret = true;
            const String strSearchPattern = "\\d{4}[0-1]\\d[0-3]\\d\\.(LOG|ZIP)";

            try
            {
                // 保持するログファイルの日数が1以上の場合
                if (0 < nStorageDateCount)
                {
                    int ndelcount = 0;
                    String strfilename;

                    // 削除対象基準日時を作成
                    DateTime dtdelbase = DateTime.Now.AddDays(-1 * nStorageDateCount);

                    // 正規表現によるファイル名マッチングパターン登録
                    Regex reg = new Regex(strSearchPattern, RegexOptions.IgnoreCase);

                    // ログファイル格納先に格納されているファイルを全て取得する
                    String[] logfiles = System.IO.Directory.GetFiles(this.m_LoggingThread.LogFolder, "*.*", System.IO.SearchOption.TopDirectoryOnly);
                    foreach (String strfile in logfiles)
                    {
                        try
                        {
                            // ファイル名(+拡張子)のみ取得
                            strfilename = System.IO.Path.GetFileName(strfile);

                            // ファイル名チェック
                            if (reg.Match(strfilename).Success == true)
                            {
                                // 有効なファイル名の場合

                                // 取得ファイルから更新日時を取得する
                                DateTime dtlastwrite = System.IO.File.GetLastWriteTime(strfile);

                                // 削除基準日時より古い場合
                                if (dtlastwrite < dtdelbase)
                                {
                                    // ファイル削除
                                    System.IO.File.Delete(strfile);

                                    ndelcount++;
                                }
                            }
                        }
                        catch (Exception ex)
                        {
#if DEBUG
                            Trace.WriteLine(String.Format("NKKLogging.DeleteLogFiles,File:{0},Error:{1}", strfile, ex.ToString()));
#endif
                            // 履歴記録
                            if (bLogging == true)
                            {
                                this.AddLogInfo(DateTime.Now, strServiceName, NKKLogging.LOGGING_CLASS.ERROR,
                                    String.Format("{0}.{1},file:{2},error:{3}", this.GetType().Name, MethodBase.GetCurrentMethod().Name, strfile, ex.ToString()));
                            }

                            bret = false;
                        }
                    }

                    // 履歴記録
                    if (bLogging == true)
                    {
                        this.AddLogInfo(DateTime.Now, strServiceName, LOGGING_CLASS.INFO, String.Format("ログ削除,{0:yyyy/MM/dd HH:mm:ss}以前,{1}件削除", dtdelbase, ndelcount));
                    }
                }
            }
            catch (Exception ex)
            {
#if DEBUG
                Trace.WriteLine(String.Format("NKKLogging.DeleteLogFiles,StrSearchPattern:{0},StorageData:{1},Error:{2}", strSearchPattern, nStorageDateCount, ex.ToString()));
#endif
                // 履歴記録
                if (bLogging == true)
                {
                    this.AddLogInfo(DateTime.Now, strServiceName, NKKLogging.LOGGING_CLASS.ERROR,
                        String.Format("{0}.{1},SearchPattern:{2},StorageData:{3},error:{4}", this.GetType().Name, MethodBase.GetCurrentMethod().Name, strSearchPattern, nStorageDateCount, ex.ToString()));
                }

                bret = false;
            }

            return (bret);
        }
