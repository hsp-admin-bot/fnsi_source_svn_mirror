            //----------------------------------------------------------------------------------------------------
            /// <summary>
            /// ログ記録用スレッドクラス デストラクタ
            /// </summary>
            //----------------------------------------------------------------------------------------------------
            public void Dispose()
            {
                try
                {
                    // ロック回避用ログ情報保持キューに内容がある場合
                    while (0 < this.m_queLogInfoBak.Count)
                    {
                        // ログ情報保持キューへロック回避用ログ情報保持キューのログ内容を移動
                        this.m_queLogInfo.Enqueue(this.m_queLogInfoBak.Dequeue());
                    };

                    // ログ情報保持キューに内容がある場合
                    while (0 < this.m_queLogInfo.Count)
                    {
                        // 全てのログをファイルに記録する
                        this.WriteLog((LOG_INFO)this.m_queLogInfo.Dequeue());

                        // 他のスレッドが処理できるように本スレッドの処理を中断する
                        Thread.Sleep(0);
                    };
                }
                catch
                {
                }
                finally
                {
                }
            }
