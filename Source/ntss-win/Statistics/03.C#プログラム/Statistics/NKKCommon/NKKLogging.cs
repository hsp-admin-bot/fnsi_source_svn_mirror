            //----------------------------------------------------------------------------------------------------
            /// <summary>
            /// ログ処理スレッド 実体
            /// </summary>
            //----------------------------------------------------------------------------------------------------
            public void DoWork()
            {
                try
                {
                    // 作業用のキュー
                    Queue queloginfo = null;
                    while (true)
                    {
                        // 書き込み処理開始指示があるまで待つ
                        this.m_LogWriteEvent.WaitOne();

                        // スレッド終了の場合
                        if (this.m_bFinish == true)
                            // 処理を抜ける
                            break;

                        // ログ情報保持キューをロック
                        lock (this.m_queLogInfo.SyncRoot)
                        {
                            // 現在までのログ情報を作業用のキューへコピー
                            queloginfo = (Queue)this.m_queLogInfo.Clone();

                            // ログ情報保持キューをクリア
                            this.m_queLogInfo.Clear();
                        }

                        // 作業用キューの内容がある場合
                        while (0 < queloginfo.Count)
                        {
                            // ファイルに記録
                            this.WriteLog((LOG_INFO)queloginfo.Dequeue());

                            // 他のスレッドが処理できるように本スレッドの処理を中断する
                            Thread.Sleep(0);
                        };

                        // 作業用キューの破棄
                        queloginfo.Clear();
                        queloginfo = null;
                    };
                }
                catch (Exception ex)
                {
                    // ログ記録
                    this.WriteLog(new LOG_INFO(this.LogExt, DateTime.Now,
                        String.Format("{0}.{1},error:{2}", this.GetType().Name, MethodBase.GetCurrentMethod().Name, ex.Message)));
                }
                finally
                {
                }
            }
