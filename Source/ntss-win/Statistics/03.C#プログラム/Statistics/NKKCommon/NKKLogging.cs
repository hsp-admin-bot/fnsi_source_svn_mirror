        /// <summary>
        /// ログ処理用クラス コンストラクタ
        /// </summary>
        //----------------------------------------------------------------------------------------------------
        private NKKLogging()
        {
            // ログ処理用スレッドクラス構築
            this.m_LoggingThread = new LoggingThread();

            // ログフォルダ格納先設定(既定：実行プログラム下のLOGフォルダ)
            this.LogFolder = String.Empty;

            // ログ処理スレッド構築、及び処理開始
            this.m_Thread = new Thread(this.m_LoggingThread.DoWork);
            this.m_Thread.Name = "ログ記録処理スレッド";
            this.m_Thread.IsBackground = false;
            this.m_Thread.Start();
        }
        //----------------------------------------------------------------------------------------------------
        /// <summary>
        /// ログ処理用クラス デストラクタ
        /// </summary>
        //----------------------------------------------------------------------------------------------------
        private void Dispose()
        {
            // スレッドが終了するまで待つ
            while (true)
            {
                // スレッドの終了を指示
                this.m_LoggingThread.StopLogThread();

                // スレッドが終了した場合
                if (this.m_Thread.IsAlive == false)
                    // 処理を抜ける
                    break;

                // 他のスレッドが処理できるように本スレッドの処理を中断する
                Thread.Sleep(0);
            };

            // ログ処理用スレッドクラス破棄
            this.m_LoggingThread.Dispose();
        }
