            /// </summary>
            /// <param name="LogInfo">ログ情報</param>
            /// <returns>true：成功/false：失敗</returns>
            //----------------------------------------------------------------------------------------------------
            private bool WriteLog(LOG_INFO LogInfo)
            {
                bool bret = false;

                try
                {
                    // ログ記録先フォルダ
                    String strfoldername = this.m_strLogFolder;

                    // ログファイル名作成
                    String strfilename = String.Empty;
                    if (String.IsNullOrEmpty(LogInfo.strLogExt) == false)
                    {
                        // mod #9696 アプリケーションログのパスとファイル名の修正。 donghao start
                        // ログ識別子がある場合
                        //strfilename = LogInfo.strLogExt;
                        if ( !"BloodPurify".Equals(Assembly.GetEntryAssembly()?.GetName().Name) && !"LayoutDesigner".Equals(Assembly.GetEntryAssembly()?.GetName().Name))
                        {
                            if (!String.IsNullOrEmpty(NKKWebAccess.FacilityCd)) {

                                strfilename = NKKWebAccess.FacilityCd + "_" + LogInfo.strLogExt;
                            }
                            else
                            {
                                strfilename = LogInfo.strLogExt;
                            }
                        }
                        else
                        {
                            strfilename = LogInfo.strLogExt;
                        }
                        // mod #9696 アプリケーションログのパスとファイル名の修正。 donghao end

                        strfilename += "_";
                    }
                    // mod #9696 アプリケーションログのパスとファイル名の修正。 limingzhe start
                    else
                    {
                        if (!String.IsNullOrEmpty(NKKWebAccess.FacilityCd))
                        {

                            strfilename = NKKWebAccess.FacilityCd + "_StatisticsTool_" + System.Net.Dns.GetHostName() + "_";
                        }
                        else
                        {
                            strfilename = "StatisticsTool_" + System.Net.Dns.GetHostName() + "_";
                        }
                    }
                    // mod #9696 アプリケーションログのパスとファイル名の修正。 limingzhe end

                    // #6843 ログアップロード LL start
                    //if ("ViewSync".Equals(LogInfo.strLogExt) && LogTime.CompareTo(DateTime.Now.ToString("HHmm")) <= 0)
                    //{
                    //    strfilename += DateTime.Now.AddDays(1).ToString("yyyyMMdd");
                    //}
                    //else
                    //{
                    //    strfilename += DateTime.Now.ToString("yyyyMMdd");
                    //}
                    // #6843 ログアップロード LL end

                    // #8510 FNSiViewSyncServiceのログが翌日の日付になる　start
                    strfilename += DateTime.Now.ToString("yyyyMMdd");
                    // #8510 FNSiViewSyncServiceのログが翌日の日付になる　end
                    strfilename += ".log";

                    // ログ保存先フォルダチェック
                    if (System.IO.Directory.Exists(strfoldername) == false)
                    {
                        // 存在しない場合

                        // ログ保存先フォルダの作成
                        System.IO.Directory.CreateDirectory(strfoldername);
                    }

                    // 初回ログ記録イベント処理チェック
                    String strfirstwritedata = String.Empty;
                    if (this.FirstWriteEvent != null)
                    {
                        // ログファイルの有無チェック、または初回ログ記録実施済みフラグチェック
                        if (System.IO.File.Exists(strfoldername + strfilename) == false || m_bFirstWriteLog == false)
                        {
                            // 存在しない、または初回ログ記録を行っていない場合

                            // 初回ログ記録イベント処理(ログの先頭に記録する情報を取得)
                            strfirstwritedata = this.FirstWriteEvent(strfoldername + strfilename);
                            if (String.IsNullOrEmpty(strfirstwritedata) == false)
                            {
                                // ログの先頭に記録する情報
                                strfirstwritedata += System.Environment.NewLine;
                            }

                            // 初回ログ記録実施済み
                            this.m_bFirstWriteLog = true;
                        }
                    }

                    // ログ末尾にCRLFがない場合は付加
                    String strlog = strfirstwritedata + LogInfo.ToString();
                    if (strlog.EndsWith(System.Environment.NewLine) == false)
                    {
                        strlog += System.Environment.NewLine;
                    }

                    // 記録情報をバイト変換
                    byte[] bbuff = this.Encoding.GetBytes(strlog);

                    // ファイルに追記
                    System.IO.FileStream fs = new System.IO.FileStream(strfoldername + strfilename, System.IO.FileMode.Append, System.IO.FileAccess.Write, System.IO.FileShare.ReadWrite);
                    fs.Write(bbuff, 0, bbuff.Length);

                    // ファイルを閉じる
                    fs.Close();

                    bret = true;
                }
                catch (Exception ex)
                {
#if DEBUG
                    Trace.WriteLine(String.Format("NKKLogging.LoggingThread.WriteLog Error:{0}", ex.ToString()));
#endif
                    //// ログ記録
                    //this.AddLogInfo(this.LogExt, DateTime.Now, String.Format("NKKLogging.LoggingThread.WriteLog(),Error,{0}", Ex.Message));
                }

                return (bret);
            }
