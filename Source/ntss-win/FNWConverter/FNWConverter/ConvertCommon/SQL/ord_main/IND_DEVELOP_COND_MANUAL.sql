WITH COND_MAXUPD_TMP AS (
	SELECT
	  PATID
	  ,PLURAL
	  ,CTL_NO
	  ,MAX(UP_DATE) MAX_UP_DATE
	  ,:DIALYSIS_DATE AS DIALYSIS_DATE
	FROM
		IND_DIALYSIS_COND
	WHERE
	PATID=:PATID
	AND  PLURAL=:PLURAL
		AND
		(:DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE)
	GROUP BY PATID, PLURAL, CTL_NO
