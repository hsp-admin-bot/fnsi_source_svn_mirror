    SELECT
        COND.PATID, COND.PLURAL, MAX(COND.IND_NO) MAX_IND_NO, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
    FROM
        IND_DIALYSIS_COND COND, COND_MAXUPD_TMP CT
    WHERE
        COND.PATID = CT.PATID
      AND COND.PLURAL = CT.PLURAL
      AND COND.CTL_NO = CT.CTL_NO
      AND COND.UP_DATE = CT.MAX_UP_DATE
      AND CT.DIALYSIS_DATE BETWEEN COND.IND_START_DATE AND COND.IND_END_DATE
    GROUP BY COND.PATID, COND.PLURAL, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
 )
