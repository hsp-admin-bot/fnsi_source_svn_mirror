WITH MAX_UPD_OFFWATER AS (
  SELECT
		PATID,
		CTL_NO,
		MAX( UP_DATE ) MAX_UP_DATE
	FROM
		PAT_REVISE_OFFWATER 
	WHERE
		{0}
		AND DAY_OF_WEEK = -1
	GROUP BY
		PATID,
		CTL_NO
		UNION ALL
		SELECT
		PATID,
		CTL_NO,
		MAX( UP_DATE ) MAX_UP_DATE
	FROM
		PAT_REVISE_OFFWATER 
	WHERE
		{0}
  AND DAY_OF_WEEK <> -1
	GROUP BY
		PATID,
		CTL_NO
)
,UPD_OFFWATER_INFO AS (
  SELECT
    RT.PATID
    ,RT.DAY_OF_WEEK
    ,RT.CTL_NO
    ,RT.UP_DATE
  FROM
    PAT_REVISE_OFFWATER RT
    INNER JOIN MAX_UPD_OFFWATER TT
      ON TT.PATID = RT.PATID
	  AND TT.CTL_NO = RT.CTL_NO
	  AND TT.MAX_UP_DATE = RT.UP_DATE
 )
,DAY_OF_WEEK_OFFWATER AS (
  SELECT
	OFFWATER.PATID
	,OFFWATER.DAY_OF_WEEK AS DAY_OF_WEEK
	,MAX(OFFWATER.UP_DATE) UP_DATE
	,MAX( CASE TT.CTL_NO WHEN 1 THEN OFFWATER.REVISE_NAME ELSE NULL END ) AS REVISE_NAME1
	,MAX( CASE TT.CTL_NO WHEN 1 THEN OFFWATER.REVISE_WEIGHT ELSE NULL END ) AS REVISE_WEIGHT1
	,MAX( CASE TT.CTL_NO WHEN 2 THEN OFFWATER.REVISE_NAME ELSE NULL END ) AS REVISE_NAME2
	,MAX( CASE TT.CTL_NO WHEN 2 THEN OFFWATER.REVISE_WEIGHT ELSE NULL END ) AS REVISE_WEIGHT2
	,MAX( CASE TT.CTL_NO WHEN 3 THEN OFFWATER.REVISE_NAME ELSE NULL END ) AS REVISE_NAME3
	,MAX( CASE TT.CTL_NO WHEN 3 THEN OFFWATER.REVISE_WEIGHT ELSE NULL END ) AS REVISE_WEIGHT3
	,MAX( CASE TT.CTL_NO WHEN 4 THEN OFFWATER.REVISE_NAME ELSE NULL END ) AS REVISE_NAME4
	,MAX( CASE TT.CTL_NO WHEN 4 THEN OFFWATER.REVISE_WEIGHT ELSE NULL END ) AS REVISE_WEIGHT4
	,MAX( CASE TT.CTL_NO WHEN 5 THEN OFFWATER.REVISE_NAME ELSE NULL END ) AS REVISE_NAME5
	,MAX( CASE TT.CTL_NO WHEN 5 THEN OFFWATER.REVISE_WEIGHT ELSE NULL END ) AS REVISE_WEIGHT5 
  FROM
	PAT_REVISE_OFFWATER OFFWATER
	INNER JOIN UPD_OFFWATER_INFO TT ON OFFWATER.PATID = TT.PATID 
	AND OFFWATER.CTL_NO = TT.CTL_NO 
	AND OFFWATER.DAY_OF_WEEK = TT.DAY_OF_WEEK 
	AND OFFWATER.UP_DATE = TT.UP_DATE 
  GROUP BY
	OFFWATER.PATID, OFFWATER.DAY_OF_WEEK
)
,DEFAULT_OFFWATER AS (
  SELECT * FROM DAY_OF_WEEK_OFFWATER WHERE DAY_OF_WEEK = -1
)
SELECT
  T1.PATID
  ,T1.UP_DATE
  ,T1.DAY_OF_WEEK
  ,NVL(T1.REVISE_NAME1, T2.REVISE_NAME1) REVISE_NAME1
  ,NVL(NVL(T1.REVISE_WEIGHT1, T2.REVISE_WEIGHT1),0) REVISE_WEIGHT1
  ,NVL(T1.REVISE_NAME2, T2.REVISE_NAME2) REVISE_NAME2
  ,NVL(NVL(T1.REVISE_WEIGHT2, T2.REVISE_WEIGHT2),0) REVISE_WEIGHT2
  ,NVL(T1.REVISE_NAME3, T2.REVISE_NAME3) REVISE_NAME3
  ,NVL(NVL(T1.REVISE_WEIGHT3, T2.REVISE_WEIGHT3),0) REVISE_WEIGHT3
  ,NVL(T1.REVISE_NAME4, T2.REVISE_NAME4) REVISE_NAME4
  ,NVL(NVL(T1.REVISE_WEIGHT4, T2.REVISE_WEIGHT4),0) REVISE_WEIGHT4
  ,NVL(T1.REVISE_NAME5, T2.REVISE_NAME5) REVISE_NAME5
  ,NVL(NVL(T1.REVISE_WEIGHT5, T2.REVISE_WEIGHT5),0) REVISE_WEIGHT5
FROM
  DAY_OF_WEEK_OFFWATER T1
  ,DEFAULT_OFFWATER T2
ORDER BY T1.PATID, T1.UP_DATE DESC