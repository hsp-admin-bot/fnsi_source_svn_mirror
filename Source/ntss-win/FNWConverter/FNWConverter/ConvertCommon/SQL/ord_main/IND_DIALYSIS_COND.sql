WITH DATE_PARAM AS ( SELECT TO_DATE( :START_DATE, 'yyyyMMdd' ) FROMDATE, TO_DATE( :END_DATE, 'yyyyMMdd' ) TODATE FROM DUAL )
,IND_DIALYSIS_COND_LIST as ( select  * from  IND_DIALYSIS_COND where (PATID,PLURAL) IN ({0}))
  ,DAY_TMP AS (
	  SELECT
		  TO_CHAR( DP.FROMDATE + rn, 'yyyyMMdd' ) AS DIALYSIS_DATE 
	  FROM
		  (SELECT ROWNUM - 1 rn FROM dual CONNECT BY ROWNUM <= ( SELECT TRUNC(TO_DATE( :END_DATE, 'yyyyMMdd' ) +1) - TRUNC(TO_DATE(:START_DATE, 'yyyyMMdd' )) FROM dual)),
		  DATE_PARAM DP 
	  WHERE
		  TO_CHAR( DP.FROMDATE + rn, 'yyyy-mm-dd' ) BETWEEN DP.FROMDATE - 1 
		  AND TO_CHAR( DP.TODATE, 'yyyy-mm-dd' )
	)
  ,COND_MAXUPD_TMP AS (
	SELECT
	  PATID
	  ,PLURAL
	  ,CTL_NO
	  ,MAX(UP_DATE) MAX_UP_DATE
	  ,DIALYSIS_DATE
	FROM
		IND_DIALYSIS_COND_LIST, DAY_TMP
	WHERE
		(DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE)
	GROUP BY PATID, PLURAL, CTL_NO, DIALYSIS_DATE
  )
  ,COND_TMP AS (
    SELECT
        COND.PATID, COND.PLURAL, MAX(COND.IND_NO) MAX_IND_NO, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
    FROM
        IND_DIALYSIS_COND_LIST COND, COND_MAXUPD_TMP CT
    WHERE
        COND.PATID = CT.PATID
      AND COND.PLURAL = CT.PLURAL
      AND COND.CTL_NO = CT.CTL_NO
      AND COND.UP_DATE = CT.MAX_UP_DATE
      AND CT.DIALYSIS_DATE BETWEEN COND.IND_START_DATE AND COND.IND_END_DATE
	  AND {1}
    GROUP BY COND.PATID, COND.PLURAL, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
)
