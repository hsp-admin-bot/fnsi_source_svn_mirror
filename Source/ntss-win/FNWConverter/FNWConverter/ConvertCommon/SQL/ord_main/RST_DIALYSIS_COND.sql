WITH V_RST_DIALYSIS_COND AS
(
SELECT
    RD.DIALYSIS_NO
    ,CASE RD.CTL_NO 
        WHEN '002' THEN '1' 
        WHEN '003' THEN '2' 
        WHEN '005' THEN '3'
        WHEN '006' THEN '006' 
        WHEN '007' THEN '4' 
        WHEN '008' THEN '5' 
        WHEN '009' THEN '6' 
        WHEN '010' THEN '14' 
        WHEN '011' THEN '25' 
        WHEN '012' THEN '26' 
        WHEN '013' THEN '27' 
        WHEN '014' THEN '28' 
        WHEN '015' THEN '29' 
        WHEN '016' THEN '31' 
        WHEN '017' THEN '32' 
        WHEN '018' THEN '15' 
        WHEN '019' THEN '16' 
        WHEN '020' THEN '17' 
        WHEN '021' THEN '18' 
        WHEN '022' THEN '19' 
        WHEN '023' THEN '20' 
        WHEN '024' THEN '21' 
        WHEN '025' THEN '23' 
        WHEN '029' THEN '12' 
        WHEN '030' THEN '22' 
        WHEN '031' THEN '30' 
        WHEN '032' THEN '34' 
        WHEN '033' THEN '35' 
        WHEN '034' THEN '36' 
        WHEN '035' THEN '37' 
        WHEN '036' THEN '38' 
        WHEN '037' THEN '33' 
        WHEN '038' THEN '24' 
        WHEN '039' THEN '7' 
        WHEN '040' THEN '8' 
        WHEN '004' THEN '39'
      END CTL_NO
    ,CASE WHEN RD.CTL_NO = '011' THEN SUBSTR(RD.VALUE, 2)
        WHEN RD.CTL_NO IN ('018', '022') THEN 
            CASE SUBSTR(RD.VALUE, 1, 1) 
                WHEN '1' THEN 'TS' || SUBSTR(RD.VALUE, 4)
                ELSE SUBSTR(RD.VALUE, 2) END
        WHEN RD.CTL_NO IN ('004','005','007','012','013','014','038') THEN
        TO_CHAR(VALUE, 'FM9999990.00') 
        WHEN RD.CTL_NO IN ('016','017','021','023','025','037') THEN
        TO_CHAR(VALUE, 'FM9999990.0') 
        WHEN RD.CTL_NO IN ('019','034','036') THEN
        TO_CHAR(RD.VALUE, 'FM9999990')
        ELSE
        RD.VALUE
        END VALUE
    ,RD.UNIT
    ,RD.VALUE_NAME1
    ,RD.VALUE_NAME2
    ,1 AS INPUT_CLASS
    ,RD.COP_ORDER_NUMBER
    ,RD.EDITABLE_FLG
    ,CASE
      WHEN RD.CTL_NO = '011'
       THEN
        CASE SUBSTR(RD.VALUE, 1, 1) WHEN '0' THEN '1' ELSE '2' END   
      WHEN RD.CTL_NO IN ('018', '022') THEN '1' END  ADD_MEDICINE_TYPE
    ,RD.DIALYSIS_ITEM_UPDATE
FROM
    RST_DIALYSIS_COND RD
    LEFT JOIN RST_DIALYSIS B ON RD.DIALYSIS_NO = B.DIALYSIS_NO
	INNER JOIN SYS_TREAT_COND_SETTING C ON C.TREAT_ITEM_CD = B.TREAT_ITEM_CD 
	AND C.COND_CTL_NO = RD.CTL_NO 
	AND C.USE_FLG = '1' 
WHERE
    {0}
    AND RD.CTL_NO NOT IN ('001', '026', '027', '028') 
)
(
  SELECT 
    DIALYSIS_NO
    ,CTL_NO
    ,VALUE
    ,UNIT
    ,VALUE_NAME1
    ,VALUE_NAME2
    ,INPUT_CLASS
    ,COP_ORDER_NUMBER
    ,EDITABLE_FLG
    ,ADD_MEDICINE_TYPE 
  FROM V_RST_DIALYSIS_COND
) 
UNION
(
  SELECT
    DIALYSIS_NO
    ,CTL_NO
    ,NULL VALUE
    ,NULL UNIT
    ,NULL VALUE_NAME1
    ,NULL VALUE_NAME2
    ,1 AS INPUT_CLASS
    ,NULL COP_ORDER_NUMBER
    ,1 EDITABLE_FLG
    ,NULL ADD_MEDICINE_TYPE 
  FROM(
    SELECT
      COND.DIALYSIS_NO
      ,MAX(DIALYSIS_ITEM_UPDATE) DIALYSIS_ITEM_UPDATE
    FROM V_RST_DIALYSIS_COND COND
    GROUP BY COND.DIALYSIS_NO
) B
CROSS JOIN (
  SELECT '9' AS CTL_NO FROM DUAL
  UNION
  SELECT '10' AS CTL_NO FROM DUAL
  UNION
  SELECT '11' AS CTL_NO FROM DUAL
  UNION
  SELECT '13' AS CTL_NO FROM DUAL
  ) C
)
ORDER BY 1,2
