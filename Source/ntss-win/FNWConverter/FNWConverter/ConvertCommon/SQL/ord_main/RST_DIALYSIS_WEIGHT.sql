WITH
WEIGHT_BEFORE_AND_AFTER AS (
{1}
)
,LOG_DEV_MSG AS (
{2}
),
LOG_LOOP_MAX AS (
	SELECT
		DIALYSIS_NO,
		PATID,
		NVL2( LOG_NUMBER1, TO_CHAR( LOG_NUMBER1 ), '' ) LOG_NUMBER1,
		NVL2( LOG_NUMBER2, TO_CHAR( LOG_NUMBER2 ), '' ) LOG_NUMBER2,
		OCCUR_DATE,
		DEVICE_NO,
		ROW_NUMBER ( ) OVER ( PARTITION BY DIALYSIS_NO ORDER BY OCCUR_DATE DESC ) AS LOG_LOOP_NUM 
	FROM
		(
		SELECT
			RD.DIALYSIS_NO,
			RD.PATID,
			LDM.OCCUR_DATE,
			NVL2( LDM.LOG_NUMBER1, TO_CHAR( LDM.LOG_NUMBER1 ), '' ) LOG_NUMBER1,
			NVL2( LDM.LOG_NUMBER2, TO_CHAR( LDM.LOG_NUMBER2 ), '' ) LOG_NUMBER2,
			LDM.DEVICE_NO
		FROM
			LOG_DEV_MSG LDM
			LEFT JOIN RST_DIALYSIS RD ON LDM.DEVICE_NO = RD.DEVICE_NO 
			AND LDM.OCCUR_DATE BETWEEN RD.START_DATE 
			AND RD.LEAVE_DATE 
		WHERE
			LDM.LOG_NUMBER1 <> - 1 
			AND {0}
		)  
	),RE_LOOP_LOG AS (
	SELECT
		DIALYSIS_NO,
		PATID,
		NVL2( LOG_NUMBER1, TO_CHAR( LOG_NUMBER1 ), '' ) LOG_NUMBER1,
		NVL2( LOG_NUMBER2, TO_CHAR( LOG_NUMBER2 ), '' ) LOG_NUMBER2,
		NVL2( OCCUR_DATE, TO_CHAR( OCCUR_DATE, 'yyyy/mm/dd hh24:mi:ss' ), '' ) OCCUR_DATE,
		ROW_NUMBER ( ) OVER ( PARTITION BY DIALYSIS_NO ORDER BY OCCUR_DATE DESC ) AS RE_LOOP_NUM
	FROM
		(
		SELECT
			RD.DIALYSIS_NO,
			RD.PATID,
			NULL SAME,
			LDM.OCCUR_DATE,
			NVL2( LDM.LOG_NUMBER1, TO_CHAR( LDM.LOG_NUMBER1 ), '' ) LOG_NUMBER1,
			NVL2( LDM.LOG_NUMBER2, TO_CHAR( LDM.LOG_NUMBER2 ), '' ) LOG_NUMBER2 
		FROM
			LOG_DEV_MSG LDM
			LEFT JOIN RST_DIALYSIS RD ON LDM.DEVICE_NO = RD.DEVICE_NO 
			AND LDM.OCCUR_DATE BETWEEN RD.START_DATE 
			AND RD.LEAVE_DATE  
		WHERE
			LDM.LOG_NUMBER1 <> - 1 
			AND {0} UNION ALL
		SELECT
			RD.DIALYSIS_NO,
			RD.PATID,
			LDM.LOG_NUMBER1 SAME,
			NULL OCCUR_DATE,
			TO_CHAR( RD.RE_LOOP_RATE ) AS LOG_NUMBER1,
			'' LOG_NUMBER2 
		FROM
			RST_DIALYSIS RD
			LEFT JOIN LOG_LOOP_MAX LDM ON LDM.DEVICE_NO = RD.DEVICE_NO 
			AND LDM.OCCUR_DATE BETWEEN RD.START_DATE 
			AND RD.LEAVE_DATE 
			AND RD.RE_LOOP_RATE <> - 1  and LOG_LOOP_NUM<=5
			AND RD.RE_LOOP_RATE IN ( LDM.LOG_NUMBER1 ) 
		WHERE
			{0}
		) 
	WHERE
		SAME IS NULL 
	)
,RE_LOOP_OTHER AS (
SELECT
		RLM.DIALYSIS_NO,
		RLM.PATID,
		RLM.LOG_NUMBER1,
		RLM.LOG_NUMBER2,
		RLM.OCCUR_DATE,
		RLM.LOG_NUM 
	FROM
		(
		SELECT
			LDM.DIALYSIS_NO,
			LDM.PATID,
			LDM.LOG_NUMBER1,
			LDM.LOG_NUMBER2,
			LDM.OCCUR_DATE,
			ROW_NUMBER ( ) OVER ( PARTITION BY LDM.DIALYSIS_NO ORDER BY LDM.OCCUR_DATE ) AS LOG_NUM 
		FROM
			RE_LOOP_LOG LDM 
		WHERE
			RE_LOOP_NUM <= 5 
		) RLM 
)
SELECT
	RD.DIALYSIS_NO,
	RD.PATID,
	RST_WEIGHT.WEIGHT_BEFORE,
	RST_WEIGHT.WEIGHT_BEFORE_DATE,
	RST_WEIGHT.WEIGHT_AFTER,
	RST_WEIGHT.WEIGHT_AFTER_DATE,
	WEIGHT_BEFORE - WEIGHT_AFTER AS WEIGHT_DECREASED,
	WEIGHT_TMP.WEIGHT_MEASURE_BEFORE,
	WEIGHT_TMP.WEIGHT_MEASURE_AFTER,
	( SELECT RO.LOG_NUMBER2 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 1 ) AS BLD1,
	( SELECT RO.LOG_NUMBER1 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 1 ) AS RATE1,
	( SELECT RO.OCCUR_DATE FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 1 ) AS DATETIME1,
	( SELECT RO.LOG_NUMBER2 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 2 ) AS BLD2,
	( SELECT RO.LOG_NUMBER1 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 2 ) AS RATE2,
	( SELECT RO.OCCUR_DATE FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 2 ) AS DATETIME2,
	( SELECT RO.LOG_NUMBER2 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 3 ) AS BLD3,
	( SELECT RO.LOG_NUMBER1 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 3 ) AS RATE3,
	( SELECT RO.OCCUR_DATE FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 3 ) AS DATETIME3,
	( SELECT RO.LOG_NUMBER2 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 4 ) AS BLD4,
	( SELECT RO.LOG_NUMBER1 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 4 ) AS RATE4,
	( SELECT RO.OCCUR_DATE FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 4 ) AS DATETIME4,
	( SELECT RO.LOG_NUMBER2 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 5 ) AS BLD5,
	( SELECT RO.LOG_NUMBER1 FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 5 ) AS RATE5,
	( SELECT RO.OCCUR_DATE FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RO.LOG_NUM = 5 ) AS DATETIME5,
	nvl(( SELECT RO.LOG_NUM FROM RE_LOOP_OTHER RO WHERE RD.DIALYSIS_NO = RO.DIALYSIS_NO AND RD.RE_LOOP_RATE = RO.LOG_NUMBER1 and ROWNUM=1 ),0) AS VALID_NO
FROM
	RST_DIALYSIS RD
	INNER JOIN RST_DIALYSIS_WEIGHT RST_WEIGHT ON RD.DIALYSIS_NO = RST_WEIGHT.DIALYSIS_NO
	LEFT JOIN WEIGHT_BEFORE_AND_AFTER WEIGHT_TMP ON WEIGHT_TMP.PATID = RD.PATID 
	AND WEIGHT_TMP.DIALYSIS_NO = RD.DIALYSIS_NO 
WHERE
    {0}
ORDER BY
    RD.DIALYSIS_NO