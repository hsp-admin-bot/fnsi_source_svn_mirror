WITH DATE_PARAM AS ( SELECT TO_DATE( :START_DATE, 'yyyyMMdd' ) FROMDATE, TO_DATE( :END_DATE, 'yyyyMMdd' ) TODATE FROM DUAL )
  ,DAY_TMP AS (
	  SELECT
		  TO_CHAR( DP.FROMDATE + rn, 'yyyyMMdd' ) AS DIALYSIS_DATE 
	  FROM
		  (SELECT ROWNUM - 1 rn FROM dual CONNECT BY ROWNUM <= ( SELECT TRUNC(TO_DATE( :END_DATE, 'yyyyMMdd' ) +1) - TRUNC(TO_DATE( :START_DATE, 'yyyyMMdd' )) FROM dual)),
		  DATE_PARAM DP 
	  WHERE
		  TO_CHAR( DP.FROMDATE + rn, 'yyyy-mm-dd' ) BETWEEN DP.FROMDATE - 1 
		  AND TO_CHAR( DP.TODATE, 'yyyy-mm-dd' )
	)
  ,COND_MAXUPD_TMP AS (
	SELECT
	  PATID
	  ,PLURAL
	  ,CTL_NO
	  ,MAX(UP_DATE) MAX_UP_DATE
	  ,DIALYSIS_DATE
	FROM
		IND_DIALYSIS_COND, DAY_TMP
	WHERE
		{0}
		AND PLURAL = 1
		AND
		(DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE)
	GROUP BY PATID, PLURAL, CTL_NO, DIALYSIS_DATE
  )
  ,COND_TMP AS (
    SELECT
        COND.PATID, COND.PLURAL, MAX(COND.IND_NO) MAX_IND_NO, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
    FROM
        IND_DIALYSIS_COND COND, COND_MAXUPD_TMP CT
    WHERE
        COND.PATID = CT.PATID
      AND COND.PLURAL = CT.PLURAL
      AND COND.CTL_NO = CT.CTL_NO
      AND COND.UP_DATE = CT.MAX_UP_DATE
      AND CT.DIALYSIS_DATE BETWEEN COND.IND_START_DATE AND COND.IND_END_DATE
    GROUP BY COND.PATID, COND.PLURAL, COND.CTL_NO, CT.MAX_UP_DATE, CT.DIALYSIS_DATE
)
SELECT DISTINCT
  COND.PATID || CT.DIALYSIS_DATE || TO_CHAR(COND.PLURAL) IND_ID
  ,COND.PATID
  ,COND.CTL_NO
  ,COND.INDICATOR_CD
  ,COND.UPDATE_STAFF_CD
  ,COND.IND_CLASS
  ,COND.VALUE_1W1N
  ,COND.VALUE_1W2N
  ,COND.VALUE_1W3N
  ,COND.VALUE_1W4N
  ,COND.VALUE_1W5N
  ,COND.VALUE_1W6N
  ,COND.VALUE_1W7N
  ,COND.VALUE_2W1N
  ,COND.VALUE_2W2N
  ,COND.VALUE_2W3N
  ,COND.VALUE_2W4N
  ,COND.VALUE_2W5N
  ,COND.VALUE_2W6N
  ,COND.VALUE_2W7N
  ,COND.DEL_FLG
  , case 
        WHEN COND.SPE_IND_FLG in (0,1) THEN '1' 
        WHEN COND.SPE_IND_FLG in (2,3) THEN '2'
      end as SPE_IND_FLG
  ,COND.PLURAL
  ,COND.COP_ORDER_NUMBER
  ,COND.EDITABLE_FLG
  ,COND.UP_DATE
FROM
  IND_DIALYSIS_COND COND
	INNER JOIN COND_TMP CT
	  ON COND.PATID = CT.PATID
	  AND COND.PLURAL = CT.PLURAL
	  AND COND.CTL_NO = CT.CTL_NO
	  AND COND.UP_DATE = CT.MAX_UP_DATE
      AND COND.IND_NO = CT.MAX_IND_NO
ORDER BY
  COND.CTL_NO