WITH RST_DIALYSIS_ALL AS (
	SELECT
		DIALYSIS.DIALYSIS_NO,
		DIALYSIS.PATID,
		DIALYSIS.UP_DATE 
	FROM
		RST_DIALYSIS DIALYSIS 
	WHERE
		{0}
		AND TO_CHAR(DIALYSIS.START_DATE, 'yyyyMMdd') BETWEEN :START_DATE AND :END_DATE
		AND DIALYSIS.DEL_FLG = '0'
		AND DIALYSIS.SERIES_CD='{4}'
	)
,MST_CHECKLIST AS (
	SELECT DISTINCT 
		DIALYSIS.LIST_CD
		,DIALYSIS.UP_DATE
		,SYS.SERIES_CD
		,DIALYSIS.ITEM_NUMBER
		,DIALYSIS.JOIN_ITEM_NUMBER
		,DIALYSIS.FUNK_FLG
		,DIALYSIS.CLASS_CD
		,CASE SYS.DIALYSIS_PROG_CD WHEN '001' THEN 0 WHEN '002' THEN 1 WHEN '003' THEN 2 END AS RST_CLASS						
	FROM SYNC_SYS_CHECKLIST DIALYSIS
		INNER JOIN SYS_CHECKLST_SETTING SYS
			ON DIALYSIS.LIST_CD = SYS.LIST_CD
			AND SYS.SERIES_CD = DIALYSIS.SERIES_CD
			AND DIALYSIS.UP_DATE = SYS.UP_DATE
			WHERE
		{0}
		AND DIALYSIS.SERIES_CD='{4}'
	)
,MST_CHECKLIST_CORRECT_PK AS (
	SELECT
		LIST_CD
		,SERIES_CD
		,MAX( MST.UP_DATE ) MAX_UP_DATE
		,RST.DIALYSIS_NO
		,RST.PATID
	FROM MST_CHECKLIST MST, RST_DIALYSIS_ALL RST 
	WHERE MST.UP_DATE < RST.UP_DATE 
	GROUP BY
		LIST_CD
		,SERIES_CD
		,RST.DIALYSIS_NO
		,RST.PATID
	)
,RST_CHECKLIST_RST AS (
	SELECT distinct
		DIALYSIS.PATID
		,DIALYSIS.DIALYSIS_NO
		,MST.LIST_CD
		,DIALYSIS.OCCUR_DATE
		,DIALYSIS.ITEM_NUMBER
		,MST.JOIN_ITEM_NUMBER
		,DIALYSIS.ITEM_NUMBER AS RST_ITEM_NUMBER
		,DIALYSIS.STAFF_CD
		,DIALYSIS.CODE
		,DIALYSIS.LIST_CD_UP_DATE
		,DIALYSIS.RESULT_NO
		,MST.FUNK_FLG
		,MST.CLASS_CD
		,MST.RST_CLASS
		,'1' AS IS_CHECK
		,DIALYSIS.UP_DATE
	FROM
		SYNC_CHECKLIST_HIST DIALYSIS 
		INNER JOIN MST_CHECKLIST MST
			ON MST.LIST_CD = DIALYSIS.LIST_CD
			AND MST.UP_DATE = DIALYSIS.LIST_CD_UP_DATE
			AND (MST.ITEM_NUMBER = DIALYSIS.ITEM_NUMBER OR REGEXP_LIKE(MST.JOIN_ITEM_NUMBER, '(^|,)'|| DIALYSIS.ITEM_NUMBER ||'(,|$)'))
	)
SELECT DISTINCT
	TMP.PATID
	,TMP.DIALYSIS_NO
	,TO_NUMBER( TMP.LIST_CD ) AS LIST_CD
	,TMP.UP_DATE
	,TO_CHAR(TMP.ITEM_NUMBER) AS ITEM_NUMBER
    ,TMP.JOIN_ITEM_NUMBER
	,TMP.OCCUR_DATE
	,TMP.STAFF_CD
	,TMP.CODE
	,TMP.RST_CLASS
	,TMP.FUNK_FLG
	,CASE WHEN TMP.RST_CLASS IN (7, 8, 9) THEN NULL
	  ELSE CASE TMP.ITEM_NUMBER
		WHEN 1 THEN SCS.LIST_ITEM_1
		WHEN 2 THEN SCS.LIST_ITEM_2
		WHEN 3 THEN SCS.LIST_ITEM_3
		WHEN 4 THEN SCS.LIST_ITEM_4
		WHEN 5 THEN SCS.LIST_ITEM_5
		WHEN 6 THEN SCS.LIST_ITEM_6
		WHEN 7 THEN SCS.LIST_ITEM_7
		WHEN 8 THEN SCS.LIST_ITEM_8
		WHEN 9 THEN SCS.LIST_ITEM_9
		WHEN 10 THEN SCS.LIST_ITEM_10
		END
	  END AS LIST_ITEM
	,TMP.CLASS_CD
	,TMP.IS_CHECK
FROM SYS_CHECKLST_SETTING SCS
  INNER JOIN (
	SELECT DISTINCT
		MST_PK.PATID
		,MST_PK.DIALYSIS_NO
		,MST.FUNK_FLG
		,MST.LIST_CD
		,MST.ITEM_NUMBER
		,MST.JOIN_ITEM_NUMBER
		,MST.CLASS_CD
		,NVL( RCC.IS_CHECK, 0 ) AS IS_CHECK
		,MST.RST_CLASS
		,RCC.OCCUR_DATE
		,RCC.STAFF_CD
		,RCC.CODE
		,NVL(RCC.LIST_CD_UP_DATE, MST.UP_DATE) AS UP_DATE
		,MST.SERIES_CD
	FROM
		MST_CHECKLIST MST
		INNER JOIN MST_CHECKLIST_CORRECT_PK MST_PK
			ON MST_PK.LIST_CD = MST.LIST_CD
			AND MST_PK.SERIES_CD = MST.SERIES_CD
			AND MST_PK.MAX_UP_DATE = MST.UP_DATE
		LEFT JOIN RST_CHECKLIST_RST RCC
			ON MST.FUNK_FLG = RCC.FUNK_FLG 
			AND MST.LIST_CD = RCC.LIST_CD 
			AND MST.UP_DATE = RCC.LIST_CD_UP_DATE
			AND MST.ITEM_NUMBER = RCC.ITEM_NUMBER
			AND RCC.DIALYSIS_NO = MST_PK.DIALYSIS_NO
	WHERE
		MST.FUNK_FLG = '0' 
	UNION ALL
	SELECT DISTINCT
		MST_PK.PATID
		,MST_PK.DIALYSIS_NO
		,MST.FUNK_FLG
		,MST.LIST_CD
		,MST.ITEM_NUMBER
		,MST.JOIN_ITEM_NUMBER
		,NVL(COND.CTL_NO, MST.CLASS_CD) AS CLASS_CD
		,NVL( RCC.IS_CHECK, 0 ) AS IS_CHECK
		,NVL2( COND.DIALYSIS_NO, MST.RST_CLASS, CASE MST.RST_CLASS WHEN 0 THEN 7 WHEN 1 THEN 8 ELSE 9 END ) AS RST_CLASS
		,RCC.OCCUR_DATE
		,RCC.STAFF_CD
		,COND.VALUE AS CODE
		,NVL(RCC.LIST_CD_UP_DATE, MST.UP_DATE) AS UP_DATE
		,MST.SERIES_CD
	FROM
		MST_CHECKLIST MST
		INNER JOIN MST_CHECKLIST_CORRECT_PK MST_PK
			ON MST_PK.LIST_CD = MST.LIST_CD
			AND MST_PK.SERIES_CD = MST.SERIES_CD
			AND MST_PK.MAX_UP_DATE = MST.UP_DATE
		LEFT JOIN (
			SELECT
				COND.DIALYSIS_NO
				,RD.PATID
				,CASE COND.CTL_NO
					WHEN '008' THEN '5'
					WHEN '009' THEN '6'
					WHEN '039' THEN '7'
					WHEN '040' THEN '8'
				  END AS CTL_NO
				,COND.VALUE 
			FROM
				RST_DIALYSIS_COND COND,
				RST_DIALYSIS_ALL RD 
			WHERE
				RD.DIALYSIS_NO = COND.DIALYSIS_NO 
				AND COND.CTL_NO IN ( '008', '009', '039', '040' ) 
				AND COND.VALUE IS NOT NULL 
			) COND
			ON MST_PK.DIALYSIS_NO = COND.DIALYSIS_NO
			AND ( MST.CLASS_CD = COND.CTL_NO OR (MST.CLASS_CD NOT IN ( '5', '6', '7', '8' ) AND COND.CTL_NO IN ( '5', '6', '7', '8' )) )
		LEFT JOIN RST_CHECKLIST_RST RCC
			ON MST.FUNK_FLG = RCC.FUNK_FLG 
			AND MST.LIST_CD = RCC.LIST_CD 
			AND MST.CLASS_CD = RCC.CLASS_CD 
			AND ( MST.ITEM_NUMBER = RCC.ITEM_NUMBER OR REGEXP_LIKE ( MST.JOIN_ITEM_NUMBER, '(^|,)' || RCC.ITEM_NUMBER || '(,|$)' ) ) 
			AND RCC.DIALYSIS_NO = MST_PK.DIALYSIS_NO
			AND MST.UP_DATE = RCC.LIST_CD_UP_DATE
			AND RCC.CODE = COND.VALUE
	WHERE
		MST.FUNK_FLG = '1'
	UNION ALL
	SELECT DISTINCT
		MST_PK.PATID
		,MST_PK.DIALYSIS_NO
		,MST.FUNK_FLG
		,MST.LIST_CD
		,MST.ITEM_NUMBER
		,MST.JOIN_ITEM_NUMBER
		,CASE EQUIP.PUNCTURE_CLASS WHEN '1' THEN '9' WHEN '2' THEN '10' WHEN '3' THEN '11' ELSE (CASE MST.CLASS_CD WHEN '203' THEN '13' ELSE MST.CLASS_CD END) END AS CLASS_CD
		,NVL( RCC.IS_CHECK, 0 ) AS IS_CHECK
		,NVL2( EQUIP.DIALYSIS_NO, MST.RST_CLASS, CASE MST.RST_CLASS WHEN 0 THEN 7 WHEN 1 THEN 8 ELSE 9 END ) AS RST_CLASS
		,RCC.OCCUR_DATE
		,RCC.STAFF_CD
		,CASE PUNCTURE_CLASS
			WHEN '3' THEN
				(CASE
				WHEN (LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0') IN (SELECT TRIM( REGEXP_SUBSTR( P_SN, '[^,]+', 1, LEVEL ) ) AS EXTRACTED_VALUE FROM SYNC_CONDSET CONNECT BY LEVEL <= REGEXP_COUNT ( P_SN, ',' ) + 1))
				THEN 'SN' || SUBSTR(LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0'), 3)
				ELSE LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0')
				END)
			ELSE LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0')
		END CODE
		,NVL(RCC.LIST_CD_UP_DATE, MST.UP_DATE) AS UP_DATE
		,MST.SERIES_CD
	FROM MST_CHECKLIST MST
		INNER JOIN MST_CHECKLIST_CORRECT_PK MST_PK
			ON MST_PK.LIST_CD = MST.LIST_CD
			AND MST_PK.SERIES_CD = MST.SERIES_CD
			AND MST_PK.MAX_UP_DATE = MST.UP_DATE
		LEFT JOIN (
	SELECT
		EQUIP.DIALYSIS_NO
		,RD.PATID
		,EQUIP.EQUIP_CD
		,EQUIP.PUNCTURE_CLASS
		,MEQUIP.EQUIP_GROUP_CD 
	FROM
		RST_DIALYSIS_EQUIP EQUIP
		,RST_DIALYSIS_ALL RD
		,MST_EQUIPMENT MEQUIP 
	WHERE
		RD.DIALYSIS_NO = EQUIP.DIALYSIS_NO 
		AND EQUIP.DEL_FLG = '0' 
		AND EQUIP.EQUIP_CD = MEQUIP.EQUIP_CD 
		AND MEQUIP.UP_DATE = ( SELECT MAX( UP_DATE ) FROM MST_EQUIPMENT WHERE EQUIP_CD = EQUIP.EQUIP_CD AND UP_DATE < EQUIP.UP_DATE ) 
	) EQUIP
			ON MST_PK.DIALYSIS_NO = EQUIP.DIALYSIS_NO
			AND MST.CLASS_CD = EQUIP.EQUIP_GROUP_CD
		LEFT JOIN RST_CHECKLIST_RST RCC
			ON MST.FUNK_FLG = RCC.FUNK_FLG 
			AND MST.LIST_CD = RCC.LIST_CD 
			AND MST.CLASS_CD = RCC.CLASS_CD 
			AND MST.ITEM_NUMBER = RCC.ITEM_NUMBER
			AND RCC.DIALYSIS_NO = MST_PK.DIALYSIS_NO
			AND MST.UP_DATE = RCC.LIST_CD_UP_DATE
			AND RCC.CODE = EQUIP.EQUIP_CD
	WHERE MST.FUNK_FLG = '2' 
) TMP
ON TMP.LIST_CD = SCS.LIST_CD
AND TMP.SERIES_CD = SCS.SERIES_CD
AND TMP.UP_DATE = SCS.UP_DATE
AND SCS.SERIES_CD='{4}'