SELECT
	RST_PLAN.PATID
	,RST_PLAN.IND_ID
	,RST_PLAN.DIALYSIS_DATE
	,RST_PLAN.BED_NO
	,RST_PLAN.KUR_CD
	,RST_PLAN.LIST_CD
	,RST_PLAN.UP_DATE
	,TO_CHAR(RST_PLAN.ITEM_NUMBER) AS ITEM_NUMBER
	,RST_PLAN.OCCUR_DATE
	,RST_PLAN.STAFF_CD
	,RST_PLAN.CODE
	,CASE MST.DIALYSIS_PROG_CD WHEN '001' THEN 0 WHEN '002' THEN 1 WHEN '003' THEN 2 END AS RST_CLASS
	,RST_PLAN.FUNK_FLG
	,CASE
		RST_PLAN.ITEM_NUMBER 
		WHEN 1 THEN MST.LIST_ITEM_1
		WHEN 2 THEN MST.LIST_ITEM_2
		WHEN 3 THEN MST.LIST_ITEM_3
		WHEN 4 THEN MST.LIST_ITEM_4
		WHEN 5 THEN MST.LIST_ITEM_5
		WHEN 6 THEN MST.LIST_ITEM_6
		WHEN 7 THEN MST.LIST_ITEM_7
		WHEN 8 THEN MST.LIST_ITEM_8
		WHEN 9 THEN MST.LIST_ITEM_9
		WHEN 10 THEN MST.LIST_ITEM_10
		END LIST_ITEM
	,RST_PLAN.CLASS_CD
	,'1' AS IS_CHECK
FROM SYS_CHECKLST_SETTING MST
INNER JOIN (
  SELECT distinct
    RC.PATID
    ,TO_NUMBER( RC.LIST_CD ) AS LIST_CD
    ,RC.OCCUR_DATE
    ,RC.ITEM_NUMBER
    ,RC.ITEM_NUMBER JOIN_ITEM_NUMBER
    ,RC.STAFF_CD
	,EQUIP.CTL_NO
    ,CASE WHEN
		EQUIP.SETTING IS NOT NULL AND EQUIP.SETTING = '3'
		THEN
        (CASE
			WHEN (LPAD(TRIM( RC.CODE ), 10, '0') IN (SELECT TRIM( REGEXP_SUBSTR( P_SN, '[^,]+', 1, LEVEL ) ) AS EXTRACTED_VALUE FROM SYNC_CONDSET CONNECT BY LEVEL <= REGEXP_COUNT ( P_SN, ',' ) + 1))
		 THEN 'SN' || SUBSTR(LPAD(TRIM( RC.CODE ), 10, '0'), 3)
        ELSE LPAD(TRIM( RC.CODE ), 10, '0')
        END)
		ELSE LPAD(TRIM( RC.CODE ), 10, '0')
      END CODE
	,RC.LIST_CD_UP_DATE
	,RC.UP_DATE
	,DIALYSIS.IND_ID
	,DIALYSIS.DIALYSIS_DATE
	,DIALYSIS.BED_NO
	,DIALYSIS.KUR_CD
    ,MST_CHECK.FUNK_FLG
    ,MST_CHECK.CLASS_CD
  FROM
    SYNC_CHECKLIST_HIST rc 
	INNER JOIN SCH_DIALYSIS_PLAN DIALYSIS
      ON DIALYSIS.PATID = RC.PATID
      AND DIALYSIS.DIALYSIS_DATE = RC.DIALYSIS_DATE
      AND DIALYSIS.BED_NO = RC.BED_NO
      AND DIALYSIS.KUR_CD = RC.KUR_CD
      AND DIALYSIS.DIALYSIS_DATE BETWEEN :START_DATE  AND :END_DATE  AND DIALYSIS.SERIES_CD='{4}'
	INNER JOIN SYNC_SYS_CHECKLIST MST_CHECK
	  ON MST_CHECK.UP_DATE = RC.LIST_CD_UP_DATE
	  AND MST_CHECK.LIST_CD = RC.LIST_CD
	  AND (MST_CHECK.ITEM_NUMBER = RC.ITEM_NUMBER OR REGEXP_LIKE(MST_CHECK.JOIN_ITEM_NUMBER, '(^|,)'|| RC.ITEM_NUMBER ||'(,|$)'))
	LEFT JOIN IND_DIALYSIS_EQUIP EQUIP
	  ON DIALYSIS.PATID = EQUIP.PATID
	  AND DIALYSIS.PLURAL = EQUIP.PLURAL
	  AND DIALYSIS.DIALYSIS_DATE BETWEEN EQUIP.IND_START_DATE AND EQUIP.IND_END_DATE
	  AND EQUIP.EQUIP_CD = RC.CODE
  WHERE DIALYSIS_NO = -1
    AND {0}
 ) RST_PLAN
	ON RST_PLAN.LIST_CD = MST.LIST_CD
	AND RST_PLAN.LIST_CD_UP_DATE = MST.UP_DATE
	AND MST.SERIES_CD = '{4}'