-- テーブル削除
-- DROP TABLE SYNC_CONV_VALUE CASCADE CONSTRAINTS;
declare
      num number;
begin
    select count(1) into num from user_tables where table_name = upper('SYNC_CONV_VALUE') ;
    if num > 0 then
        execute immediate 'drop table SYNC_CONV_VALUE CASCADE CONSTRAINTS' ;
    end if;
end;
/
-- テーブル作成
CREATE TABLE SYNC_CONV_VALUE
(
    NTSS_TABLE_NAME VARCHAR2(50),  --NTSSテーブル名
    NTSS_COLUMN_NAME VARCHAR2(50),  --NTSSカラム名
    NTSS_JSON_NAME VARCHAR2(50),  --NTSSJSONキー名
    XML_CONFIG_NAME VARCHAR2(150),  --XML設定名
    FNW_COLUMN_NAME VARCHAR2(50),  --FNWカラム名
    SORT NUMBER,  --ソート順
    TARGET_VALUE VARCHAR2(50),  --変換前の値
    CONV_VALUE VARCHAR2(1000),  --変換後の値
    MEMO VARCHAR2(100),  --メモ
    DECISION_TARGET_COLUMN_NAME VARCHAR2(30),  --対象カラム
    CONVERSION_TYPE VARCHAR2(30)  --変換種別
)
    tablespace NKK_DATA_COP;
-- コメント追加
COMMENT ON TABLE "SYNC_CONV_VALUE" IS '設定値変換定義';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."NTSS_TABLE_NAME" IS 'NTSSテーブル名';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."NTSS_COLUMN_NAME" IS 'NTSSカラム名';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."NTSS_JSON_NAME" IS 'NTSSJSONキー名';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."XML_CONFIG_NAME" IS 'XML設定名';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."FNW_COLUMN_NAME" IS 'FNWカラム名';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."SORT" IS 'ソート順';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."TARGET_VALUE" IS '変換前の値';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."CONV_VALUE" IS '変換後の値';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."MEMO" IS 'メモ';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."DECISION_TARGET_COLUMN_NAME" IS '対象カラム';
COMMENT ON COLUMN "SYNC_CONV_VALUE"."CONVERSION_TYPE" IS '変換種別';
