INSERT
	INTO
		V_PAT_REVISE_OFFWATER(
			PATID,
			NAME,
			CTL_NO,
			UP_DATE,
			REVISE_NAME,
			REVISE_WEIGHT,
			MON_UP_DATE,
			MON_REVISE_NAME,
			MON_REVISE_WEIGHT,
			TUE_UP_DATE,
			TUE_REVISE_NAME,
			TUE_REVISE_WEIGHT,
			WED_UP_DATE,
			WED_REVISE_NAME,
			WED_REVISE_WEIGHT,
			THU_UP_DATE,
			THU_REVISE_NAME,
			THU_REVISE_WEIGHT,
			FRI_UP_DATE,
			FRI_REVISE_NAME,
			FRI_REVISE_WEIGHT,
			SAT_UP_DATE,
			SAT_REVISE_NAME,
			SAT_REVISE_WEIGHT,
			SUN_UP_DATE,
			SUN_REVISE_NAME,
			SUN_REVISE_WEIGHT	
		)SELECT
		CASE WHEN LENGTHB(hosppatid) > 12 THEN SUBSTRB(hosppatid, -12) ELSE hosppatid END,
		CASE WHEN LENGTHB(name) > 200 THEN SUBSTRB(name, -200) ELSE name END, 
		CASE WHEN LENGTHB(ctlno) > 3 THEN SUBSTRB(ctlno, -3) ELSE ctlno END,
		TO_DATE("update",'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(revisename) > 512 THEN SUBSTRB(revisename, -512) ELSE revisename END,
		reviseweight,
		TO_DATE(monupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(monrevisename) > 512 THEN SUBSTRB(monrevisename, -512) ELSE monrevisename END,
		monreviseweight,
		TO_DATE(tueupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(tuerevisename) > 512 THEN SUBSTRB(tuerevisename, -512) ELSE tuerevisename END,
		tuereviseweight,
		TO_DATE(wedupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(wedrevisename) > 512 THEN SUBSTRB(wedrevisename, -512) ELSE wedrevisename END,
		wedreviseweight,
		TO_DATE(thuupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(thurevisename) > 512 THEN SUBSTRB(thurevisename, -512) ELSE thurevisename END,
		thureviseweight,
		TO_DATE(friupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(frirevisename) > 512 THEN SUBSTRB(frirevisename, -512) ELSE frirevisename END,
		frireviseweight,
		TO_DATE(satupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(satrevisename) > 512 THEN SUBSTRB(satrevisename, -512) ELSE satrevisename END,
		satreviseweight,
		TO_DATE(sunupdate,'yyyy-mm-dd hh24:mi:ss'),
		CASE WHEN LENGTHB(sunrevisename) > 512 THEN SUBSTRB(sunrevisename, -512) ELSE sunrevisename END, 
		sunreviseweight
		FROM V_PAT_REVISE_OFFWATER_TEMP

