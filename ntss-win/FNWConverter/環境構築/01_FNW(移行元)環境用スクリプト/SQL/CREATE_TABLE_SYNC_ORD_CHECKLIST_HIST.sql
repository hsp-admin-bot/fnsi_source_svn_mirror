COMMENT ON COLUMN "SYNC_ORD_CHECKLIST_HIST"."CODE" IS '医材コード';
COMMENT ON COLUMN "SYNC_ORD_CHECKLIST_HIST"."RST_CHECK_COUNT" IS '実際チェック';

