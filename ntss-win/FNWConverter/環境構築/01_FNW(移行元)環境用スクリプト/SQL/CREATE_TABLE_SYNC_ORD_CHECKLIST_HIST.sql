(
	PATID VARCHAR2(50),
	IND_ID VARCHAR2(50),
	DIALYSIS_DATE VARCHAR2(20),
	BED_NO NUMBER(4,0),
	KUR_CD CHAR(3),
	CODE CHAR(10),
	RST_CHECK_COUNT NUMBER,
	UP_DATE DATE
)
    tablespace NKK_DATA_COP;
