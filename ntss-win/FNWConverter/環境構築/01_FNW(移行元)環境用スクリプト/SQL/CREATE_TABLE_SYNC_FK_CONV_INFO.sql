-- テーブル削除
-- DROP TABLE SYNC_FK_CONV_INFO CASCADE CONSTRAINTS;
declare
      num number;
begin
    select count(1) into num from user_tables where table_name = upper('SYNC_FK_CONV_INFO') ;
    if num > 0 then
        execute immediate 'drop table SYNC_FK_CONV_INFO CASCADE CONSTRAINTS' ;
    end if;
end;
/
-- テーブル作成
CREATE TABLE SYNC_FK_CONV_INFO
(
    NTSS_TABLE_NAME VARCHAR2(50),  --NTSSテーブル名
    NTSS_COLUMN_NAME VARCHAR2(50),  --NTSSカラム名
    NTSS_JSON_NAME VARCHAR2(50),  --NTSSJSONキー名
    SELECT_TABLE_NAME VARCHAR2(70),  --検索対象テーブル
    SELECT_COLUMN_NAME VARCHAR2(70),  --検索対象カラム名
    CONDITION_COLUMN_NAME VARCHAR2(50),  --条件指定カラム
    IS_FACILITY_CD VARCHAR2(50),  --施設コード使用フラグ
    OTHER_CONDITION VARCHAR2(100)  --その他条件
)
    tablespace NKK_DATA_COP;
-- コメント追加
COMMENT ON TABLE "SYNC_FK_CONV_INFO" IS 'テーブル参照変換定義';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."NTSS_TABLE_NAME" IS 'NTSSテーブル名';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."NTSS_COLUMN_NAME" IS 'NTSSカラム名';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."NTSS_JSON_NAME" IS 'NTSSJSONキー名';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."SELECT_TABLE_NAME" IS '検索対象テーブル';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."SELECT_COLUMN_NAME" IS '検索対象カラム名';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."CONDITION_COLUMN_NAME" IS '条件指定カラム';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."IS_FACILITY_CD" IS '施設コード使用フラグ';
COMMENT ON COLUMN "SYNC_FK_CONV_INFO"."OTHER_CONDITION" IS 'その他条件';
