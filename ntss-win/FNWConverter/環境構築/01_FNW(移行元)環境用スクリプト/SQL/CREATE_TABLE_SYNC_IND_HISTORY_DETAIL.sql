-- テーブル削除
declare
      num number;
begin
    select count(1) into num from user_tables where table_name = upper('SYNC_IND_HISTORY_DETAIL') ;
    if num > 0 then
        execute immediate 'DROP TABLE SYNC_IND_HISTORY_DETAIL CASCADE CONSTRAINTS' ;
    end if;
end;
/
-- テーブル作成
CREATE TABLE SYNC_IND_HISTORY_DETAIL
(
    PATID CHAR(128),
    TAKER_CD CHAR(10),
    TAKER_NAME VARCHAR2(20),
    CATEGORY_CD CHAR(3) NOT NULL,
    CONFIRM_ID NUMBER NOT NULL,
    MNG_NO NUMBER(8) NOT NULL,
    CATEGORY_SUB_NO CHAR(7) NOT NULL,
    UP_DATE DATE NOT NULL,
    PRIMARY KEY (CONFIRM_ID, MNG_NO, CATEGORY_CD, CATEGORY_SUB_NO, UP_DATE)
)
    tablespace NKK_DATA_COP;
-- コメント追加
COMMENT ON TABLE "SYNC_IND_HISTORY_DETAIL" IS '前回指示履歴コンバートデータバックアップテーブル';

COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.PATID IS '患者ID';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.TAKER_CD IS '確認者コード';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.TAKER_NAME IS '確認者名';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.CATEGORY_CD IS 'カテゴリコード';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.CONFIRM_ID IS '指示確認ID';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.MNG_NO IS '管理番号';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.CATEGORY_SUB_NO IS 'カテゴリサブ番号';
COMMENT ON COLUMN SYNC_IND_HISTORY_DETAIL.UP_DATE IS 'レコード更新日時';