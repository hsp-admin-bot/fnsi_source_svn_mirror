	SELECT
		MST.LIST_CD
		,DIALYSIS.PATID
		,MST.SERIES_CD
		,MAX( MST.UP_DATE ) UP_DATE
		,TO_CHAR( DIALYSIS.DIALYSIS_NO ) DIALYSIS_KEY 
	FROM
		SYS_CHECKLST_SETTING MST,
