		AND MST_PK.UP_DATE = SYS.UP_DATE 
		AND MST_PK.SERIES_CD = SYS.SERIES_CD 
	WHERE
	   SYS.SERIES_CD = '{4}'　AND 
		(FUNK_FLAG_1 = '1' OR FUNK_FLAG_2 = '1' OR FUNK_FLAG_3 = '1' 
