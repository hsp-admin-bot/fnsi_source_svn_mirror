	,LISTAGG ( ITEM_NUMBER, ',' ) WITHIN GROUP ( ORDER BY LIST_CD, UP_DATE, SERIES_CD, DIALYSIS_KEY, PATID ) AS JOIN_ITEM_NUMBER
	,MIN(ITEM_NUMBER) ITEM_NUMBER
	,LIST_CD
	,'1' FUNK_FLG
	,'5' CLASS_CD
	,UP_DATE
	,SERIES_CD 
	FROM
		MST_CHECKLIST 
	WHERE
		FUNK_FLG = '1' 
		AND CLASS_CD = '5' 
