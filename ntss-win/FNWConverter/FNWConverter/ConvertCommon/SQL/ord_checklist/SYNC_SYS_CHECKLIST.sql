	SELECT
		DIALYSIS.DIALYSIS_NO
		,DIALYSIS.PATID
		,DIALYSIS.UP_DATE 
	FROM RST_DIALYSIS DIALYSIS 
	WHERE
		{0}
		AND TO_CHAR(DIALYSIS.START_DATE, 'yyyyMMdd') BETWEEN :START_DATE AND :END_DATE 
		AND DIALYSIS.DEL_FLG = '0'
		AND DIALYSIS.SERIES_CD = '{4}'
	) DIALYSIS 
	WHERE
		MST.UP_DATE < DIALYSIS.UP_DATE 
		AND MST.SERIES_CD = '{4}'
	GROUP BY
		LIST_CD
		,SERIES_CD
		,DIALYSIS.DIALYSIS_NO
		,DIALYSIS.PATID
	UNION ALL
	SELECT
		MST.LIST_CD
		,DIALYSIS.PATID
		,MST.SERIES_CD
		,MST.UP_DATE UP_DATE
		,DIALYSIS.IND_ID DIALYSIS_KEY 
	FROM
		SYS_CHECKLST_SETTING MST,
		(
	SELECT DISTINCT
		DIALYSIS.IND_ID
		,DIALYSIS.PATID
		,RC.LIST_CD
		,RC.LIST_CD_UP_DATE 
	FROM
		SYNC_CHECKLIST_HIST rc 
		INNER JOIN SCH_DIALYSIS_PLAN DIALYSIS
		ON {0}
		AND RC.DIALYSIS_NO = - 1 
		AND DIALYSIS.PATID = RC.PATID 
		AND DIALYSIS.DIALYSIS_DATE = RC.DIALYSIS_DATE 
		AND DIALYSIS.BED_NO = RC.BED_NO 
		AND DIALYSIS.KUR_CD = RC.KUR_CD 
		AND DIALYSIS.DIALYSIS_DATE BETWEEN :START_DATE  AND :END_DATE
		and DIALYSIS.SERIES_CD='{4}'
	) DIALYSIS 
	WHERE
		MST.UP_DATE = DIALYSIS.LIST_CD_UP_DATE 
		AND MST.LIST_CD = DIALYSIS.LIST_CD 
		AND MST.SERIES_CD = '{4}'
	)
