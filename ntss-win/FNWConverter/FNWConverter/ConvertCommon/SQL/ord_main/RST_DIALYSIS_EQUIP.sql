SELECT
  0 AS EQUIP_TYPE
  ,DIALYSIS_NO
  ,CASE PUNCTURE_CLASS
    WHEN '3' THEN
        (CASE
        WHEN (LPAD(TRIM(EQUIP_CD), 10, '0') IN (SELECT TRIM( REGEXP_SUBSTR( P_SN, '[^,]+', 1, LEVEL ) ) AS EXTRACTED_VALUE FROM SYNC_CONDSET CONNECT BY LEVEL <= REGEXP_COUNT ( P_SN, ',' ) + 1))
        THEN 'SN' || SUBSTR(LPAD(TRIM(EQUIP_CD), 10, '0'), 3)
        ELSE LPAD(TRIM(EQUIP_CD), 10, '0')
        END)
    ELSE LPAD(TRIM(EQUIP_CD), 10, '0')
    END EQUIP_CD
  ,EQUIP_NAME
  ,AMOUNT
  ,UNIT
  ,COP_ORDER_NUMBER
  ,EQUIP_CLASS_NAME
  ,EDITABLE_FLG
  ,PUNCTURE_CLASS
FROM
    RST_DIALYSIS_EQUIP RD
WHERE
    {0}
    AND DEL_FLG = '0'
order by
    DIALYSIS_NO
    , CTL_NO
