WITH DATE_PARAM AS ( SELECT TO_DATE( :START_DATE, 'YYYYMMDD' ) FROMDATE, TO_DATE( :END_DATE, 'YYYYMMDD' ) TODATE FROM DUAL )
  ,DAY_TMP AS (
	  SELECT
		  TO_CHAR( DP.FROMDATE + rn, 'YYYYMMDD' ) AS DIALYSIS_DATE 
	  FROM
		  (SELECT ROWNUM - 1 rn FROM dual CONNECT BY ROWNUM <= ( SELECT TRUNC(TO_DATE( :END_DATE, 'YYYYMMDD' ) +1) - TRUNC(TO_DATE( :START_DATE, 'YYYYMMDD' )) FROM dual)),
		  DATE_PARAM DP 
	  WHERE
		  TO_CHAR( DP.FROMDATE + rn, 'YYYY-MM-DD' ) BETWEEN DP.FROMDATE - 1 
		  AND TO_CHAR( DP.TODATE, 'YYYY-MM-DD' )
	),  /*+ MATERIALIZE */ SCH_DIALYSIS_PLAN_list  as (select  IND_ID ,UP_DATE from SCH_DIALYSIS_PLAN where {1}  ),
	
 
 /*+ MATERIALIZE */ IND_DIALYSIS_MEDI_list  as (
 select a.* from   IND_DIALYSIS_MEDI a  WHERE
	(PATID,PLURAL) IN ({0}) 
 )
  ,MEDI_MAXUPD_TMP AS (
    SELECT
        PATID, PLURAL, CTL_NO, MAX(m.UP_DATE) MAX_UP_DATE, DIALYSIS_DATE
    FROM
        IND_DIALYSIS_MEDI_list m INNER JOIN
		DAY_TMP  d on   DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE
	    INNER JOIN SCH_DIALYSIS_PLAN_list s on s.ind_id=PATID ||DIALYSIS_DATE||PLURAL 
    GROUP BY PATID, PLURAL, CTL_NO, DIALYSIS_DATE
  )
  ,MEDI_TMP AS (
    SELECT
        MEDI.PATID, MEDI.PLURAL, MAX(MEDI.IND_NO) MAX_IND_NO, MEDI.CTL_NO, MT.MAX_UP_DATE, MT.DIALYSIS_DATE
    FROM
        IND_DIALYSIS_MEDI_list MEDI, MEDI_MAXUPD_TMP MT
    WHERE
        MEDI.PATID = MT.PATID
      AND MEDI.PLURAL = MT.PLURAL
      AND MEDI.CTL_NO = MT.CTL_NO
      AND MEDI.UP_DATE = MT.MAX_UP_DATE
      AND MT.DIALYSIS_DATE BETWEEN MEDI.IND_START_DATE AND MEDI.IND_END_DATE
    GROUP BY MEDI.PATID, MEDI.PLURAL, MEDI.CTL_NO, MT.MAX_UP_DATE, MT.DIALYSIS_DATE
  )
  ,CLASS_NAME_TMP as (
	SELECT
		CLASS_CD
		,CLASS_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY CLASS_CD ORDER BY CLASS_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_CLASS_NAME where CLASS_KIND = '3'
  )
  ,SET_MEDI_TMP as (
	SELECT
		SET_MEDICINE_CD
		,MEDICINE_GROUP_CD
		,UNIT
		,SET_MEDICINE_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY SET_MEDICINE_CD ORDER BY SET_MEDICINE_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_SET_MEDI_NAME
  )
  ,MST_MEDI_TMP as (
	SELECT
		MEDICINE_CD
		,MEDICINE_GROUP_CD
		,UNIT
		,MEDICINE_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY MEDICINE_CD ORDER BY MEDICINE_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_MEDICINE
  )
   ,MST_STAFF_NEW AS (
	SELECT
		STAFF_CD,
		UP_DATE,
		TRIM(REGEXP_REPLACE( REGEXP_REPLACE( TRIM( BOTH ' ' FROM TRIM( BOTH '　' FROM STAFF_NAME ) ), '　', ' ' ), '\s+', ' ')) AS STAFF_NAME
	FROM MST_STAFF
  )
  ,STAFF_TMP AS (
	SELECT
		STAFF_CD
		,CASE WHEN instr( STAFF_NAME, ' ' ) = 0 THEN STAFF_NAME
			WHEN instr( STAFF_NAME, ' ' ) > 0 THEN substr( STAFF_NAME, 0, instr( STAFF_NAME, ' ' ) - 1 ) 
			END AS LAST_NAME
		,CASE WHEN instr( STAFF_NAME, ' ' ) > 0 THEN substr( STAFF_NAME, instr( STAFF_NAME, ' ' ) + 1 ) ELSE ' ' END AS FIRST_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY STAFF_CD ORDER BY STAFF_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_STAFF_NEW
  )
SELECT DISTINCT
  MEDI.PATID || MT.DIALYSIS_DATE || TO_CHAR(MEDI.PLURAL) IND_ID
  ,MEDI.PATID
  ,MT.DIALYSIS_DATE
  ,SM.NO as CTL_NO
  ,MEDI.SET_MEDICINE_FLG
  ,MEDI.MEDICINE_CD
  ,CASE MEDI.SET_MEDICINE_FLG
	WHEN '0' THEN MEDI_INFO.MEDICINE_GROUP_CD
	WHEN '1' THEN SET_MEDI.MEDICINE_GROUP_CD
	END CLASS_CD
  ,CASE MEDI.SET_MEDICINE_FLG
	WHEN '0' THEN CLASS_NAME.CLASS_NAME
	WHEN '1' THEN SET_CLASS_NAME.CLASS_NAME
	END CLASS_NAME
  ,CASE MEDI.SET_MEDICINE_FLG
	WHEN '0' THEN MEDI_INFO.MEDICINE_NAME
	WHEN '1' THEN SET_MEDI.SET_MEDICINE_NAME
	END MEDICINE_NAME
  ,CASE MEDI.SET_MEDICINE_FLG
	WHEN '0' THEN MEDI_INFO.UNIT
	WHEN '1' THEN SET_MEDI.UNIT
	END UNIT
  ,MEDI.VALUE_1W1N
  ,MEDI.VALUE_1W2N
  ,MEDI.VALUE_1W3N
  ,MEDI.VALUE_1W4N
  ,MEDI.VALUE_1W5N
  ,MEDI.VALUE_1W6N
  ,MEDI.VALUE_1W7N
  ,MEDI.VALUE_2W1N
  ,MEDI.VALUE_2W2N
  ,MEDI.VALUE_2W3N
  ,MEDI.VALUE_2W4N
  ,MEDI.VALUE_2W5N
  ,MEDI.VALUE_2W6N
  ,MEDI.VALUE_2W7N
  ,MEDI.VALUE_3W1N
  ,MEDI.VALUE_3W2N
  ,MEDI.VALUE_3W3N
  ,MEDI.VALUE_3W4N
  ,MEDI.VALUE_3W5N
  ,MEDI.VALUE_3W6N
  ,MEDI.VALUE_3W7N
  ,MEDI.VALUE_4W1N
  ,MEDI.VALUE_4W2N
  ,MEDI.VALUE_4W3N
  ,MEDI.VALUE_4W4N
  ,MEDI.VALUE_4W5N
  ,MEDI.VALUE_4W6N
  ,MEDI.VALUE_4W7N
  ,MEDI.COUNT_EVERY_MONTH
  ,MEDI.TIMING_CD
  ,TIMING.TIMING_NAME
  ,MEDI.PROCEDURE_CD
  ,PROCEDURER.PROCEDURE_NAME
  ,MEDI.COMMENTS
  ,MEDI.INDICATOR_CD
  ,INDICATOR.FIRST_NAME INDICATOR_FIRST_NAME
  ,INDICATOR.LAST_NAME INDICATOR_LAST_NAME
  ,MEDI.UPDATE_STAFF_CD
  ,UPDATER.FIRST_NAME UPDATE_STAFF_FIRST_NAME
  ,UPDATER.LAST_NAME UPDATE_STAFF_LAST_NAME
  ,CASE 
    WHEN MEDI.SPE_IND_FLG IN (0,1) THEN '1' 
    WHEN MEDI.SPE_IND_FLG IN (2,3) THEN '2'
   END SPE_IND_FLG
  ,MEDI.COP_ORDER_NUMBER
  ,MEDI.EDITABLE_FLG
  ,MEDI.PLURAL
  ,MEDI.IND_START_DATE
  ,MEDI.DAY_PATTERN
  ,MEDI.DEL_FLG
FROM
  IND_DIALYSIS_MEDI_list MEDI 
    INNER JOIN MEDI_TMP MT
      ON MEDI.PATID = MT.PATID
      AND MEDI.PLURAL = MT.PLURAL
      AND MEDI.CTL_NO = MT.CTL_NO
      AND MEDI.UP_DATE = MT.MAX_UP_DATE
      AND MEDI.IND_NO = MT.MAX_IND_NO
    LEFT JOIN SYNC_MEDICINE_LATEST_NO SM on  SM.PATID=MEDI.PATID and SM.IND_NO=MEDI.CTL_NO and SM.PLURAL=MEDI.PLURAL  and SM.SERIES_CD='{SERIES_CD}'
		
		LEFT JOIN SCH_DIALYSIS_PLAN_list s on s.IND_ID=MEDI.PATID || MT.DIALYSIS_DATE || TO_CHAR( MEDI.PLURAL ) 
	
	LEFT JOIN MST_MEDI_TMP MEDI_INFO ON MEDI_INFO.MEDICINE_CD = MEDI.MEDICINE_CD AND s.UP_DATE BETWEEN MEDI_INFO.UP_DATE AND MEDI_INFO.END_DATE
	
	LEFT JOIN SET_MEDI_TMP SET_MEDI ON SET_MEDI.SET_MEDICINE_CD = MEDI.MEDICINE_CD AND s.UP_DATE BETWEEN SET_MEDI.UP_DATE AND SET_MEDI.END_DATE
	
	LEFT JOIN CLASS_NAME_TMP CLASS_NAME ON CLASS_NAME.CLASS_CD = SET_MEDI.MEDICINE_GROUP_CD AND s.UP_DATE BETWEEN CLASS_NAME.UP_DATE AND CLASS_NAME.END_DATE
	
	LEFT JOIN CLASS_NAME_TMP SET_CLASS_NAME ON SET_CLASS_NAME.CLASS_CD = SET_MEDI.MEDICINE_GROUP_CD AND s.UP_DATE BETWEEN SET_CLASS_NAME.UP_DATE AND SET_CLASS_NAME.END_DATE
	
	LEFT JOIN STAFF_TMP INDICATOR ON INDICATOR.STAFF_CD = MEDI.INDICATOR_CD AND s.UP_DATE BETWEEN INDICATOR.UP_DATE AND INDICATOR.END_DATE
	
	LEFT JOIN STAFF_TMP UPDATER ON UPDATER.STAFF_CD = MEDI.INDICATOR_CD AND s.UP_DATE BETWEEN UPDATER.UP_DATE AND UPDATER.END_DATE
	
	LEFT JOIN (
		SELECT
			TIMING_CD
			,TIMING_NAME 
			,UP_DATE
			,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY TIMING_CD ORDER BY TIMING_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
		FROM MST_TIMING
	) TIMING ON MEDI.TIMING_CD = TIMING.TIMING_CD AND s.UP_DATE BETWEEN TIMING.UP_DATE AND TIMING.END_DATE
	
	LEFT JOIN (
		SELECT
			PROCEDURE_CD
			,PROCEDURE_NAME 
			,UP_DATE
			,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY PROCEDURE_CD ORDER BY PROCEDURE_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
		FROM MST_PROCEDURE
	) PROCEDURER ON MEDI.PROCEDURE_CD = PROCEDURER.PROCEDURE_CD AND s.UP_DATE BETWEEN PROCEDURER.UP_DATE AND PROCEDURER.END_DATE
ORDER BY
  SM.NO