WITH DATE_PARAM AS ( SELECT TO_DATE(:START_DATE, 'yyyyMMdd' ) FROMDATE, TO_DATE(:END_DATE, 'yyyyMMdd' ) TODATE FROM DUAL )
,IND_DIALYSIS_EQUIP_LIST as ( select  * from  IND_DIALYSIS_EQUIP where (PATID,PLURAL) IN ({0}))
  ,DAY_TMP AS (
	  SELECT
		  TO_CHAR( DP.FROMDATE + rn, 'yyyyMMdd' ) AS DIALYSIS_DATE 
	  FROM
		  (SELECT ROWNUM - 1 rn FROM dual CONNECT BY ROWNUM <= ( SELECT TRUNC(TO_DATE(:END_DATE, 'yyyyMMdd' ) +1) - TRUNC(TO_DATE( :START_DATE, 'yyyyMMdd' )) FROM dual)),
		  DATE_PARAM DP 
	  WHERE
		  TO_CHAR( DP.FROMDATE + rn, 'yyyy-mm-dd' ) BETWEEN DP.FROMDATE - 1 
		  AND TO_CHAR( DP.TODATE, 'yyyy-mm-dd' )
	)
  ,EQUIP_MAXUPD_TMP AS (
	SELECT
		PATID, PLURAL, CTL_NO, MAX(UP_DATE) MAX_UP_DATE, DIALYSIS_DATE
	FROM
		IND_DIALYSIS_EQUIP_LIST, DAY_TMP
	WHERE
		(DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE)
	GROUP BY PATID, PLURAL, CTL_NO, DIALYSIS_DATE
  )
  ,EQUIP_TMP AS (
    SELECT
        EQUIP.PATID, EQUIP.PLURAL, MAX(EQUIP.IND_NO) MAX_IND_NO, EQUIP.CTL_NO, ET.MAX_UP_DATE, ET.DIALYSIS_DATE
    FROM
        IND_DIALYSIS_EQUIP_LIST EQUIP, EQUIP_MAXUPD_TMP ET
    WHERE
        EQUIP.PATID = ET.PATID
      AND EQUIP.PLURAL = ET.PLURAL
      AND EQUIP.CTL_NO = ET.CTL_NO
      AND EQUIP.UP_DATE = ET.MAX_UP_DATE
      AND ET.DIALYSIS_DATE BETWEEN EQUIP.IND_START_DATE AND EQUIP.IND_END_DATE
      AND {1}
    GROUP BY EQUIP.PATID, EQUIP.PLURAL, EQUIP.CTL_NO, ET.MAX_UP_DATE, ET.DIALYSIS_DATE
)
SELECT
  EQUIP.PATID || ET.DIALYSIS_DATE || TO_CHAR(EQUIP.PLURAL) IND_ID
  ,EQUIP.CTL_NO
  ,EQUIP.PATID
  ,0 EQUIP_TYPE
  ,EQUIP.SETTING
  ,CASE EQUIP.SETTING
    WHEN '3' THEN
        (CASE
        WHEN (LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0') IN (SELECT TRIM( REGEXP_SUBSTR( P_SN, '[^,]+', 1, LEVEL ) ) AS EXTRACTED_VALUE FROM SYNC_CONDSET CONNECT BY LEVEL <= REGEXP_COUNT ( P_SN, ',' ) + 1))
        THEN 'SN' || SUBSTR(LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0'), 3)
        ELSE LPAD(TRIM(EQUIP.EQUIP_CD), 10, '0')
        END)
    ELSE LPAD(TRIM(EQUIP_CD), 10, '0')
    END EQUIP_CD
  ,EQUIP.VALUE_1W1N
  ,EQUIP.VALUE_1W2N
  ,EQUIP.VALUE_1W3N
  ,EQUIP.VALUE_1W4N
  ,EQUIP.VALUE_1W5N
  ,EQUIP.VALUE_1W6N
  ,EQUIP.VALUE_1W7N
  ,EQUIP.VALUE_2W1N
  ,EQUIP.VALUE_2W2N
  ,EQUIP.VALUE_2W3N
  ,EQUIP.VALUE_2W4N
  ,EQUIP.VALUE_2W5N
  ,EQUIP.VALUE_2W6N
  ,EQUIP.VALUE_2W7N
  ,EQUIP.INDICATOR_CD
  ,EQUIP.UPDATE_STAFF_CD
  ,EQUIP.SPE_IND_FLG
  ,EQUIP.COP_ORDER_NUMBER
  ,EQUIP.EDITABLE_FLG
  ,EQUIP.DAY_PATTERN
  ,EQUIP.DEL_FLG
FROM
  IND_DIALYSIS_EQUIP_LIST EQUIP
    INNER JOIN EQUIP_TMP ET
      ON EQUIP.PATID = ET.PATID
	  AND EQUIP.PLURAL = ET.PLURAL
	  AND EQUIP.CTL_NO = ET.CTL_NO
	  AND EQUIP.UP_DATE = ET.MAX_UP_DATE
      AND EQUIP.IND_NO = ET.MAX_IND_NO
   LEFT JOIN  (SELECT DISTINCT IND_ID,OPE_IND_PLAN FROM( SELECT IND_ID,OPE_IND_PLAN FROM  SCH_DIALYSIS_PLAN WHERE  OPE_IND_PLAN='1' UNION ALL SELECT  PATID|| IND_START_DATE||PLURAL AS IND_ID , OPE_IND_PLAN 
     FROM   IND_DIALYSIS_PLAN WHERE  OPE_IND_PLAN='1') ) s ON   s.IND_ID=EQUIP.PATID || ET.DIALYSIS_DATE || TO_CHAR(EQUIP.PLURAL)
	WHERE  (s.IND_ID IS NOT NULL AND s.OPE_IND_PLAN = EQUIP.OPE_IND_PLAN)
    OR s.IND_ID IS NULL
ORDER BY
  EQUIP.CTL_NO