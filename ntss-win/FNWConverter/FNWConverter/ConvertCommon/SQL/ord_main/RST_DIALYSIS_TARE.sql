SELECT
  TMP.DIALYSIS_NO
  ,TMP.ORDER_CLASS
  ,MAX(CASE TMP.SEQ WHEN 1 THEN TMP.CTL_NO ELSE NULL END) AS CTL_NO1
  ,MAX(CASE TMP.SEQ WHEN 1 THEN TMP.REVISE_NAME ELSE NULL END) AS REVISE_NAME1
  ,NVL(MAX(CASE TMP.SEQ WHEN 1 THEN TMP.REVISE_WEIGHT ELSE NULL END),0) AS REVISE_WEIGHT1
  ,MAX(CASE TMP.SEQ WHEN 2 THEN TMP.CTL_NO ELSE NULL END) AS CTL_NO2
  ,MAX(CASE TMP.SEQ WHEN 2 THEN TMP.REVISE_NAME ELSE NULL END) AS REVISE_NAME2
  ,NVL(MAX(CASE TMP.SEQ WHEN 2 THEN TMP.REVISE_WEIGHT ELSE NULL END),0) AS REVISE_WEIGHT2
  ,MAX(CASE TMP.SEQ WHEN 3 THEN TMP.CTL_NO ELSE NULL END) AS CTL_NO3
  ,MAX(CASE TMP.SEQ WHEN 3 THEN TMP.REVISE_NAME ELSE NULL END) AS REVISE_NAME3
  ,NVL(MAX(CASE TMP.SEQ WHEN 3 THEN TMP.REVISE_WEIGHT ELSE NULL END),0) AS REVISE_WEIGHT3
  ,MAX(CASE TMP.SEQ WHEN 4 THEN TMP.CTL_NO ELSE NULL END) AS CTL_NO4
  ,MAX(CASE TMP.SEQ WHEN 4 THEN TMP.REVISE_NAME ELSE NULL END) AS REVISE_NAME4
  ,NVL(MAX(CASE TMP.SEQ WHEN 4 THEN TMP.REVISE_WEIGHT ELSE NULL END),0) AS REVISE_WEIGHT4
  ,MAX(CASE TMP.SEQ WHEN 5 THEN TMP.CTL_NO ELSE NULL END) AS CTL_NO5
  ,MAX(CASE TMP.SEQ WHEN 5 THEN TMP.REVISE_NAME ELSE NULL END) AS REVISE_NAME5
  ,NVL(MAX(CASE TMP.SEQ WHEN 5 THEN TMP.REVISE_WEIGHT ELSE NULL END),0) AS REVISE_WEIGHT5
  ,MAX(CASE TMP.SEQ WHEN 6 THEN TMP.HOSP_WHEELCHAIR_CD ELSE NULL END) AS WHEEL_CHAIR_CD
  ,MAX(CASE TMP.SEQ WHEN 6 THEN TMP.REVISE_NAME ELSE NULL END) AS WHEEL_CHAIR_NAME
  ,MAX(CASE TMP.SEQ WHEN 6 THEN TMP.REVISE_WEIGHT ELSE NULL END) AS WHEEL_CHAIR_WEIGHT
FROM
(
  SELECT
    DIALYSIS_NO
    ,CTL_NO
    ,ORDER_CLASS
    ,REVISE_NAME
    ,REVISE_WEIGHT
    ,HOSP_WHEELCHAIR_CD
    ,ROW_NUMBER() OVER (PARTITION BY DIALYSIS_NO,ORDER_CLASS ORDER BY DIALYSIS_NO,ORDER_CLASS,CTL_NO) AS SEQ
  FROM
    RST_DIALYSIS_TARE
  WHERE
    ORDER_CLASS IN ('0', '1')
) TMP
WHERE DIALYSIS_NO IN ({0})
GROUP BY
    TMP.DIALYSIS_NO, TMP.ORDER_CLASS