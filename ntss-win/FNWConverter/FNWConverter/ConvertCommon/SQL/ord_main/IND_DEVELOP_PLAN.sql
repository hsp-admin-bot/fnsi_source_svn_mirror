WITH IND_DEVELOP_PLAN_NEW AS (
	SELECT
		IND_ID,
		DIALYSIS_DATE,
		KUR_CD,
		KUR_NAME,
		BED_NO,
		BED_NAME,
		INDICATOR_CD,
		UPDATE_STAFF_CD,
  		SPE_IND_FLG,
  		PLURAL,
  		OPE_IND_PLAN,
        TRIM(REGEXP_REPLACE( REGEXP_REPLACE( TRIM( BOTH ' ' FROM TRIM( BOTH '　' FROM UPDATE_STAFF_NAME ) ), '　', ' ' ), '\s+', ' ')) AS UPDATE_STAFF_NAME_NEW,
        TRIM(REGEXP_REPLACE( REGEXP_REPLACE( TRIM( BOTH ' ' FROM TRIM( BOTH '　' FROM INDICATOR_NAME ) ), '　', ' ' ), '\s+', ' ')) AS INDICATOR_NAME_NEW
	FROM
		IND_DEVELOP_PLAN
        WHERE
        {0}
)
SELECT
  IND_ID
  ,DIALYSIS_DATE
  ,KUR_CD
  ,KUR_NAME
  ,BED_NO
  ,BED_NAME
  ,INDICATOR_CD
  ,case when instr(UPDATE_STAFF_NAME_NEW,' ')=0 then UPDATE_STAFF_NAME_NEW
      when instr(UPDATE_STAFF_NAME_NEW,' ')>0 then substr(UPDATE_STAFF_NAME_NEW,0,instr(UPDATE_STAFF_NAME_NEW,' ')-1)
    end as UPD_USER_LAST_NAME
  ,case when instr(UPDATE_STAFF_NAME_NEW,' ')>0 then substr(UPDATE_STAFF_NAME_NEW,instr(UPDATE_STAFF_NAME_NEW,' ')+1)
      else ' '
    end as UPD_USER_FIRST_NAME
  ,UPDATE_STAFF_CD
  ,case when instr(INDICATOR_NAME_NEW,' ')=0 then INDICATOR_NAME_NEW
      when instr(INDICATOR_NAME_NEW,' ')>0 then substr(INDICATOR_NAME_NEW,0,instr(INDICATOR_NAME_NEW,' ')-1)
    end as IND_USER_LAST_NAME
  ,case when instr(INDICATOR_NAME_NEW,' ')>0 then substr(INDICATOR_NAME_NEW,instr(INDICATOR_NAME_NEW,' ')+1)
      else ' '
    end as IND_USER_FIRST_NAME
  ,CASE 
     WHEN SPE_IND_FLG in (0,1) THEN '1' 
     WHEN SPE_IND_FLG in (2,3) THEN '2'
    END SPE_IND_FLG
  ,PLURAL
  ,OPE_IND_PLAN
FROM
  IND_DEVELOP_PLAN_NEW 

ORDER BY
  IND_ID