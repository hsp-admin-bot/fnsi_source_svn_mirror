WITH DAY_TMP AS (
	  SELECT
		TO_CHAR( TO_DATE(:DIALYSIS_DATE, 'YYYYMMDD' ), 'YYYYMMDD' ) AS DIALYSIS_DATE 
	FROM
		DUAL
	)
,PLAN_DAY_TMP AS (
  SELECT
    DT.DIALYSIS_DATE
    ,IND_PLAN.PATID
    ,IND_PLAN.PLURAL
    ,IND_PLAN.OPE_IND_PLAN
    ,TO_CHAR( TO_DATE( DT.DIALYSIS_DATE, 'YYYY-MM-DD' ), 'D' ) - 1 YOBI
    ,IND_PLAN.IND_START_DATE
    ,IND_PLAN.IND_END_DATE
    ,IND_PLAN.IND_NO
    ,IND_PLAN.UP_DATE
    ,CASE WHEN
        IND_PLAN.CYCLE_WEEK != 2
        OR
        (IND_PLAN.CYCLE_WEEK = 2 AND 0 = MOD( TO_CHAR( TO_DATE( IND_PLAN.IND_START_DATE, 'YYYYMMDD' ), 'IW' ) - TO_CHAR( TO_DATE( DT.DIALYSIS_DATE, 'YYYYMMDD' ), 'IW' ), 2 ))
        THEN
        CASE
            ( TO_CHAR( TO_DATE( DT.DIALYSIS_DATE, 'YYYY-MM-DD' ), 'D' ) - 1 )
            WHEN 1 THEN VALUE_1W1N
            WHEN 2 THEN VALUE_1W2N
            WHEN 3 THEN VALUE_1W3N
            WHEN 4 THEN VALUE_1W4N
            WHEN 5 THEN VALUE_1W5N
            WHEN 6 THEN VALUE_1W6N
            WHEN 0 THEN VALUE_1W7N
        END
        ELSE
        CASE
            ( TO_CHAR( TO_DATE( DT.DIALYSIS_DATE, 'YYYY-MM-DD' ), 'D' ) - 1 )
            WHEN 1 THEN VALUE_2W1N
            WHEN 2 THEN VALUE_2W2N
            WHEN 3 THEN VALUE_2W3N
            WHEN 4 THEN VALUE_2W4N
            WHEN 5 THEN VALUE_2W5N
            WHEN 6 THEN VALUE_2W6N
            WHEN 0 THEN VALUE_2W7N
        END
        END VALUE
	,IND_PLAN.CYCLE_WEEK
    ,IND_PLAN.INDICATOR_CD
    ,IND_PLAN.UPDATE_STAFF_CD
  FROM
    IND_DIALYSIS_PLAN IND_PLAN,
    DAY_TMP DT
  WHERE
    IND_PLAN.OPE_IND_PLAN = '0'
    AND IND_PLAN.IND_CLASS  <> '1'
    AND IND_PLAN.PATID = :PATID
    AND IND_PLAN.PLURAL =:PLURAL
    AND (DT.DIALYSIS_DATE BETWEEN IND_PLAN.IND_START_DATE AND IND_PLAN.IND_END_DATE)
)
,SINGLE_PLAN_DAY_TMP AS (
  SELECT
    DT.DIALYSIS_DATE
    ,IND_PLAN.PATID
    ,IND_PLAN.PLURAL
    ,IND_PLAN.OPE_IND_PLAN
    ,TO_CHAR( TO_DATE( DT.DIALYSIS_DATE, 'YYYY-MM-DD' ), 'D' ) - 1 YOBI
    ,IND_PLAN.VALUE_1W1N VALUE
    ,IND_PLAN.IND_START_DATE
    ,IND_PLAN.IND_END_DATE
    ,IND_PLAN.IND_NO
    ,IND_PLAN.UP_DATE
    ,IND_PLAN.DEL_FLG
	,IND_PLAN.CYCLE_WEEK
    ,IND_PLAN.INDICATOR_CD
    ,IND_PLAN.UPDATE_STAFF_CD
  FROM
    IND_DIALYSIS_PLAN IND_PLAN,
    DAY_TMP DT
  WHERE
    IND_PLAN.OPE_IND_PLAN = '1'
    AND IND_PLAN.IND_CLASS  <> '1'
    AND IND_PLAN.PATID = :PATID
    AND IND_PLAN.PLURAL =:PLURAL
	AND ( DT.DIALYSIS_DATE BETWEEN IND_PLAN.IND_START_DATE AND IND_PLAN.IND_END_DATE )
)
,UPDATE_TMP AS ( SELECT PATID, DIALYSIS_DATE, MAX( UP_DATE ) MAX_UP_DATE, PLURAL FROM PLAN_DAY_TMP WHERE DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE GROUP BY PATID, DIALYSIS_DATE, PLURAL )
,SINGLE_UPDATE_TMP AS (
  SELECT
    PATID,
    DIALYSIS_DATE,
    PLURAL,
    MAX( UP_DATE ) MAX_UP_DATE
  FROM
    SINGLE_PLAN_DAY_TMP
  WHERE
    DIALYSIS_DATE BETWEEN IND_START_DATE AND IND_END_DATE GROUP BY PATID, DIALYSIS_DATE, PLURAL
)

,MST_STAFF_NEW AS (
	SELECT
		STAFF_CD,
		UP_DATE,
		TRIM(REGEXP_REPLACE( REGEXP_REPLACE( TRIM( BOTH ' ' FROM TRIM( BOTH '　' FROM STAFF_NAME ) ), '　', ' ' ), '\s+', ' ')) AS STAFF_NAME
	FROM MST_STAFF
  )
,STAFF_TMP AS (
	SELECT
		STAFF_CD
		,CASE WHEN instr( STAFF_NAME, ' ' ) = 0 THEN STAFF_NAME
			WHEN instr( STAFF_NAME, ' ' ) > 0 THEN substr( STAFF_NAME, 0, instr( STAFF_NAME, ' ' ) - 1 ) 
			END AS LAST_NAME
		,CASE WHEN instr( STAFF_NAME, ' ' ) > 0 THEN substr( STAFF_NAME, instr( STAFF_NAME, ' ' ) + 1 ) ELSE ' ' END AS FIRST_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY STAFF_CD ORDER BY STAFF_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_STAFF_NEW
  )
,BED_TMP AS (
	SELECT
		BED_NO
		,BED_NAME
		,REG_DATE AS UP_DATE
		,NVL( LEAD ( REG_DATE, 1, NULL ) OVER ( PARTITION BY BED_NO ORDER BY BED_NO, REG_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_BED
  )
,KUR_TMP AS (
	SELECT
		KUR_CD
		,KUR_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY KUR_CD ORDER BY KUR_CD, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_KUR
  )
,DIALYSIS_PLAN AS (
  SELECT
    IND_PLAN.DIALYSIS_DATE
    ,IND_PLAN.PATID
    ,IND_PLAN.PLURAL
    ,IND_PLAN.VALUE
    ,CASE SUBSTR( IND_PLAN.VALUE, 0, 4 ) WHEN 'NON' THEN 0 ELSE TO_NUMBER(SUBSTR( IND_PLAN.VALUE, 0, 4 )) END AS BED_NO
    ,SUBSTR( IND_PLAN.VALUE, 5, 3 ) KUR_CD
    ,IND_PLAN.OPE_IND_PLAN
    ,IND_PLAN.CYCLE_WEEK
    ,IND_PLAN.INDICATOR_CD
    ,IND_PLAN.UPDATE_STAFF_CD
    ,IND_PLAN.UP_DATE
  FROM PLAN_DAY_TMP IND_PLAN
    INNER JOIN UPDATE_TMP
      ON UPDATE_TMP.PATID = IND_PLAN.PATID
      AND UPDATE_TMP.DIALYSIS_DATE = IND_PLAN.DIALYSIS_DATE
      AND IND_PLAN.UP_DATE = UPDATE_TMP.MAX_UP_DATE AND UPDATE_TMP.PLURAL = IND_PLAN.PLURAL
    
  WHERE
    LENGTH( IND_PLAN.VALUE ) >= 8
    AND IND_PLAN.IND_NO = (
          SELECT MAX( IND_NO ) FROM PLAN_DAY_TMP PDT
          WHERE PDT.PATID = IND_PLAN.PATID AND IND_PLAN.UP_DATE = PDT.UP_DATE AND IND_PLAN.PLURAL = PDT.PLURAL AND PDT.DIALYSIS_DATE = IND_PLAN.DIALYSIS_DATE 												
        )
  UNION ALL
  SELECT
    IND_PLAN.DIALYSIS_DATE
    ,IND_PLAN.PATID
    ,IND_PLAN.PLURAL
    ,IND_PLAN.VALUE
    ,CASE SUBSTR( IND_PLAN.VALUE, 0, 4 ) WHEN 'NON' THEN 0 ELSE TO_NUMBER(SUBSTR( IND_PLAN.VALUE, 0, 4 )) END AS BED_NO
    ,SUBSTR( IND_PLAN.VALUE, 5, 3 ) KUR_CD
    ,IND_PLAN.OPE_IND_PLAN
    ,IND_PLAN.CYCLE_WEEK
    ,IND_PLAN.INDICATOR_CD
    ,IND_PLAN.UPDATE_STAFF_CD
    ,IND_PLAN.UP_DATE
  FROM SINGLE_PLAN_DAY_TMP IND_PLAN
    INNER JOIN SINGLE_UPDATE_TMP UPDATE_TMP
      ON UPDATE_TMP.PATID = IND_PLAN.PATID
      AND UPDATE_TMP.DIALYSIS_DATE = IND_PLAN.DIALYSIS_DATE
      AND UPDATE_TMP.MAX_UP_DATE = IND_PLAN.UP_DATE
      AND UPDATE_TMP.PLURAL = IND_PLAN.PLURAL
    
    WHERE
      IND_PLAN.DEL_FLG = '0'
      AND LENGTH( IND_PLAN.VALUE ) >= 8
      AND IND_PLAN.IND_NO = (
        SELECT MAX( IND_NO )
        FROM SINGLE_PLAN_DAY_TMP PDT
        WHERE PDT.PATID = IND_PLAN.PATID AND IND_PLAN.UP_DATE = PDT.UP_DATE AND IND_PLAN.PLURAL = PDT.PLURAL AND PDT.DIALYSIS_DATE = IND_PLAN.DIALYSIS_DATE 												
      )
)
SELECT
  S.DIALYSIS_DATE
  ,S.PATID
  ,S.PLURAL
  ,TO_CHAR( S.PATID ) || TO_CHAR( S.DIALYSIS_DATE ) || TO_CHAR(S.PLURAL ) IND_ID
  ,('"'|| S.PATID ||'","'|| S.PLURAL|| '"' ) IND_ID_CONNECT
  ,S.VALUE
  ,S.BED_NO
  ,BT.BED_NAME
  ,S.KUR_CD
  ,KT.KUR_NAME
  ,CASE S.OPE_IND_PLAN WHEN '1' THEN '0' ELSE TO_CHAR(S.CYCLE_WEEK) END AS CYCLE_WEEK
  ,CASE TO_CHAR(TO_DATE(S.DIALYSIS_DATE, 'yyyyMMdd'), 'D') 
        WHEN '1' THEN 7
        WHEN '2' THEN 1
        WHEN '3' THEN 2
        WHEN '4' THEN 3
        WHEN '5' THEN 4
        WHEN '6' THEN 5
        WHEN '7' THEN 6
        END ADD_TREAT_WEEK
  ,S.OPE_IND_PLAN
  ,S.INDICATOR_CD
  ,INDICATOR.FIRST_NAME INDICATOR_FIRST_NAME
  ,INDICATOR.LAST_NAME INDICATOR_LAST_NAME
  ,S.UPDATE_STAFF_CD
  ,UPDATER.FIRST_NAME UPDATE_STAFF_FIRST_NAME
  ,UPDATER.LAST_NAME UPDATE_STAFF_LAST_NAME
  ,'' OFF_WATER
  ,'' TARE
  ,S.UP_DATE
FROM
  DIALYSIS_PLAN S
	LEFT JOIN STAFF_TMP INDICATOR ON INDICATOR.STAFF_CD = S.INDICATOR_CD AND TO_DATE(:SCHUPDATE, 'yyyy-mm-dd hh24:mi:ss') BETWEEN INDICATOR.UP_DATE AND INDICATOR.END_DATE
	LEFT JOIN STAFF_TMP UPDATER ON UPDATER.STAFF_CD = S.INDICATOR_CD AND TO_DATE(:SCHUPDATE, 'yyyy-mm-dd hh24:mi:ss') BETWEEN UPDATER.UP_DATE AND UPDATER.END_DATE
	LEFT JOIN BED_TMP BT ON BT.BED_NO = S.BED_NO AND TO_DATE(:SCHUPDATE, 'yyyy-mm-dd hh24:mi:ss') BETWEEN BT.UP_DATE AND BT.END_DATE
	LEFT JOIN KUR_TMP KT ON KT.KUR_CD = S.KUR_CD AND TO_DATE(:SCHUPDATE, 'yyyy-mm-dd hh24:mi:ss') BETWEEN KT.UP_DATE AND KT.END_DATE

