WITH CONVERT_HISTORY AS(
select * from sync_convert_history a
inner join sync_convert_history_dtl b
on (a.seq_no=b.seq_no) where table_kind = 'ORD'
),
RST_SEND_CONDITION_ALL AS(
{1}
),
RST_DIALYSIS_NEW AS(
SELECT DIALYSIS_NO,PATID as PATID_NEW,LEAVE_DATE,ENTER_DATE,DEVICE_NO,BED_NO,KUR_CD FROM RST_DIALYSIS
)
SELECT
rsc.DEVICE_NO,
rsc.PATID,
rsc.BED_NO,
rsc.KUR_CD,
rsc.DIALYSIS_DATE,
rsc.RESEND_DATE,
rsc.SET_DATA,
CASE WHEN rsc.SEND_STATUS=0 AND rsc.SET_CD=0 THEN 0
     WHEN rsc.SEND_STATUS=1 AND rsc.SET_CD=0 THEN 1
     WHEN rsc.SET_CD=1 THEN 2
	ELSE 4
	END TREAT_CLASS,
'1' as IS_DISP,	
'0' as IS_DEL,
c.DIALYSIS_NO,
BEFORE_WEIGHT,	
DW,
rsc.TARGET_WEIGHT,	
rsc.MEASURE_WEIGHT,	
rsc.OFFWATER_LIMIT,
trim(rsc.OFFWATER_CORRECT_CODE1) as OFFWATER_CORRECT_CODE1,	
nvl(rsc.OFFWATER_CORRECT_VALUE1,0) as OFFWATER_CORRECT_VALUE1,	
rsc.OFFWATER_UPDATE_DAY1,	
trim(rsc.OFFWATER_CORRECT_CODE2) as OFFWATER_CORRECT_CODE2,	
nvl(rsc.OFFWATER_CORRECT_VALUE2,0) as OFFWATER_CORRECT_VALUE2,	
rsc.OFFWATER_UPDATE_DAY2,	
trim(rsc.OFFWATER_CORRECT_CODE3) as OFFWATER_CORRECT_CODE3,	
nvl(rsc.OFFWATER_CORRECT_VALUE3,0) as OFFWATER_CORRECT_VALUE3,	
rsc.OFFWATER_UPDATE_DAY3,	
trim(rsc.OFFWATER_CORRECT_CODE4) as OFFWATER_CORRECT_CODE4,	
nvl(rsc.OFFWATER_CORRECT_VALUE4,0) as OFFWATER_CORRECT_VALUE4,	
rsc.OFFWATER_UPDATE_DAY4,	
trim(rsc.OFFWATER_CORRECT_CODE5) as OFFWATER_CORRECT_CODE5,	
nvl(rsc.OFFWATER_CORRECT_VALUE5,0) as OFFWATER_CORRECT_VALUE5,	
rsc.OFFWATER_UPDATE_DAY5,	
rsc.TARE_CORRECT_CODE1,	
rsc.TARE_CORRECT_VALUE1,	
rsc.TARE_UPDATE_DAY1,	
rsc.TARE_CORRECT_CODE2,	
rsc.TARE_CORRECT_VALUE2,	
rsc.TARE_UPDATE_DAY2,	
rsc.TARE_CORRECT_CODE3,	
rsc.TARE_CORRECT_VALUE3,	
rsc.TARE_UPDATE_DAY3,	
rsc.TARE_CORRECT_CODE4,	
rsc.TARE_CORRECT_VALUE4,	
rsc.TARE_UPDATE_DAY4,	
rsc.TARE_CORRECT_CODE5,	
rsc.TARE_CORRECT_VALUE5,	
rsc.TARE_UPDATE_DAY5,	
rsc.TARE_CORRECT_CODE6,	
rsc.TARE_CORRECT_VALUE6,	
rsc.TARE_UPDATE_DAY6,	
rsc.WHEEL_CHAIR_CD,	
rsc.WHEEL_CHAIR_UPDATE,
NVL(rsc.OFFWATER_TARGET,0) as　OFFWATER_TARGET,
NVL( rsc.OFFWATER_CORRECT_VALUE1, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE2, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE3, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE4, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE5, 0 ) as  OFFWATER_CORRECT_VALUEALL,
rsc.BEFORE_WEIGHT - NVL(rsc.TARGET_WEIGHT, 0 ) + ( NVL( rsc.OFFWATER_CORRECT_VALUE1, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE2, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE3, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE4, 0 ) + NVL( rsc.OFFWATER_CORRECT_VALUE5, 0 )) as CALCULATEDVALUE
FROM
	RST_SEND_CONDITION_ALL rsc
	INNER JOIN  MST_DEVICE d on d.DEVICE_NO=rsc.DEVICE_NO {2} 
	and NOT EXISTS ( SELECT * FROM MST_DEVICE b WHERE d.DEVICE_NO = b.DEVICE_NO AND d.UP_DATE <b.UP_DATE )
　　left outer join RST_DIALYSIS_NEW c on(rsc.PATID=c.PATID_NEW 
	AND rsc.RESEND_DATE <= c.LEAVE_DATE AND rsc.RESEND_DATE >= c.ENTER_DATE
	AND rsc.DEVICE_NO = c.DEVICE_NO)
	{0}
ORDER BY
	rsc.DEVICE_NO