WITH PAT_BASIC_INFO_NORMAL AS ( SELECT PATID, DISP_PATID FROM PAT_BASIC_INFO GROUP BY PATID, DISP_PATID )
,CONVERT_HISTORY AS {0}
,EVENT_CLASS_LIST AS ( SELECT 
    cem.EVENT_GROUP_NO,
    cem.COOP_ID,
    cem.EVENT_CLASS,
    cem.EVENT_SEQ_NUMBER,
    cem.SPECIFIC_KEY,
    cem.KEY_INFO,
    cem.PROC_FLG,
    cem.EVENT_OCCUR_DATE,
    cem.COOP_FUNCTION_NAME,
    ccsh.UP_DATE
FROM 
    COP_EVENT_MANAGE cem
LEFT JOIN 
    COP_COOP_SEND_HST ccsh 
    ON cem.EVENT_GROUP_NO = ccsh.EVENT_GROUP_NO
    AND cem.COOP_ID = ccsh.COOP_ID
    AND cem.EVENT_SEQ_NUMBER = ccsh.EVENT_SEQ_NUMBER
INNER JOIN 
    CONVERT_HISTORY CH 
    ON (cem.EVENT_OCCUR_DATE > CH.CONVERT_DATETIME OR 
       (ccsh.UP_DATE IS NOT NULL AND ccsh.UP_DATE > CH.CONVERT_DATETIME))  WHERE cem.SERIES_CD = '{SERIES_CD}' AND PROC_FLG = '1' )
SELECT  PATID FROM (
	SELECT
	CASE
		 WHEN CEM.COOP_ID IN( 'EGM01','FNX01') THEN 'INI_DIAL'
		 WHEN CEM.COOP_ID IN('EGM02','FNX02','STD01','40000','NEC01','NIS01','NIS03','SNY01','TSM02','THC01','50000','KOB01','BML01' 
					,'SSI02','SCM01','SCM10','KIC01','STD12','STD14','IMS01','EGM00','FNX03','60000','NIS00','SNY05','THC00','50100','KOB02' 
					,'KOB03','KIC02','STD13','STD15','STD16','IMS00','IMS02','FF001') THEN 'PROFILE' 
		 WHEN CEM.COOP_ID IN( 'SNY02' ,'BML02','SCM04') THEN 'ACCEPT' 
		 WHEN CEM.COOP_ID IN( 'SSI01','HBR01','STD17') THEN 'ORD_DIAL' 
		 WHEN CEM.COOP_ID IN( 'EGM03','TYKW1','FNX04','NEC07','NIS04','41000','TSM03','IBM01','SSI05','SCM02','STD11','IMS06' ,'CCS00','YYM02') THEN 'IND_DIAL' 
		 WHEN CEM.COOP_ID IN( 'EGM04','FNX05','FCX01','FSX01','STD03','NEC04','NIS05','42000','SNY04','TSM04','THC02','IBM02','SSI04','SCM03','ICY03' 
									,'SSM01','IMS07','CCS01') THEN 'RST_DIAL' 
		 WHEN CEM.COOP_ID IN( 'SNY03' ,'SSI03','SCM08') THEN 'KARTE_ORD'
		 WHEN CEM.COOP_ID IN( 'EGM05','PDF00','45000','NEC06','NIS06','FXR01','SCM09','KIC03','GHJ01','YKG01') THEN 'REP_DIAL' 
		 WHEN CEM.COOP_ID IN( 'EGM07','FNX06','FCX02','46000','STD07','SCM05','ICY01','SNY08','STD09') THEN 'EXAM_ORD' 
		 WHEN CEM.COOP_ID IN( 'EGM06','FNX07','00008','NIS02','54000','SNY06','TSM05','TSM06','54100','STD02','STD10','IMS04','IMS03') THEN 'EXAM_RST' 
		 WHEN CEM.COOP_ID IN( 'EGM08','SCM06')THEN 'RAD_ORD' 
		 WHEN CEM.COOP_ID = 'EGM09' THEN 'PHY_ORD' 
		 WHEN CEM.COOP_ID IN( 'EGM12', 'NEC15' , '53000', '53100' , 'IMS05') THEN 'STAFF_MST' 
		 WHEN CEM.COOP_ID IN( 'EGM10','NEC12' ,'NEC13' ,'NEC17','ICY06') THEN 'SHOT_ORD' 
		 WHEN CEM.COOP_ID IN('PLP01','FKD01','NEC16') THEN 'VIT_COP' 
		 WHEN CEM.COOP_ID IN( 'NEC14','ICY02','STD08','EGM11') THEN 'PRE_ORD' 
		 END AS COOP_CD,
	CASE WHEN CEM.COOP_ID IN( 'EGM03', 'TYKW1', 'FNX04' , 'NEC07','NIS04','41000','TSM03','IBM01','SSI05','SCM02','STD11','IMS06','CCS00' ,'YYM02') THEN
			SUBSTR( CEM.SPECIFIC_KEY,- 13, 12 ) 
		 WHEN CEM.COOP_ID IN( 'EGM02','FNX02','STD01','40000','NEC01','NIS01','NIS03','SNY01','TSM02','THC01' ,'50000','KOB01','BML01','SSI02','SCM01' 
							,'SCM10','KIC01','STD12','STD14','IMS01','EGM00','FNX03','60000','NIS00','SNY05','THC00','50100' ,'KOB02','KOB03','KIC02' 
							,'STD13','STD15','STD16','IMS00','IMS02','FF001') THEN P.PATID 
		ELSE ( SELECT PATID FROM RST_DIALYSIS WHERE DIALYSIS_NO = SUBSTR( CEM.SPECIFIC_KEY, 1, 12 ) ) 
		END AS PATID ,
		case
			when cem.COOP_ID ='EGM03' or cem.COOP_ID ='TYKW1' or cem.COOP_ID ='FNX04' or cem.COOP_ID ='NEC07' or cem.COOP_ID ='NIS04' or cem.COOP_ID ='41000' or cem.COOP_ID ='TSM03'
			or cem.COOP_ID ='IBM01' or cem.COOP_ID ='SSI05' or cem.COOP_ID ='SCM02'  or cem.COOP_ID ='STD11' or cem.COOP_ID ='IMS06' or cem.COOP_ID ='CCS00' or cem.COOP_ID ='YYM02'
			then substr(cem.SPECIFIC_KEY,0,8)
			when cem.COOP_FUNCTION_NAME in ('透析条件送信', '透析実績','バイタル送信','透析レポート','レポートストア')
			then TO_CHAR(RE.START_DATE,'yyyyMMdd')
			else TO_CHAR(cem.EVENT_OCCUR_DATE,'yyyyMMdd')
			end
			as START_DATE
	FROM
	EVENT_CLASS_LIST  CEM
	LEFT JOIN RST_DIALYSIS RE ON TO_CHAR(RE.DIALYSIS_NO)=CEM.SPECIFIC_KEY
	LEFT JOIN PAT_BASIC_INFO_NORMAL P ON P.DISP_PATID =(LPAD( SUBSTR (KEY_INFO, INSTR(KEY_INFO,'<DISP_PATID>') + 12, INSTR(KEY_INFO,'</DISP_PATID>')-INSTR(KEY_INFO,'<DISP_PATID>')-12),12,0))
	
) A
      INNER JOIN CONVERT_HISTORY CH ON A.START_DATE >= CH.START_DATE
	  AND A.START_DATE <= CH.END_DATE 
WHERE
COOP_CD IS NOT NULL 
and ( COOP_CD = 'profile' or ( A.START_DATE >= :START_DATE))
GROUP BY PATID

