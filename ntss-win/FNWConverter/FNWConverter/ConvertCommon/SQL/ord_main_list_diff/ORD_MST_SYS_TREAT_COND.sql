WITH COND_MAXUPD_TMP AS ( SELECT PATID, PLURAL,IND_NO, MAX( UP_DATE ) MAX_UP_DATE FROM IND_DIALYSIS_COND WHERE CTL_NO = '006'  GROUP BY PATID, PLURAL,IND_NO ),
COND_TMP AS (
	SELECT
		COND.PATID,
		COND.PLURAL,
		MAX( COND.IND_NO ) MAX_IND_NO,
		CT.MAX_UP_DATE 
	FROM
		IND_DIALYSIS_COND COND,
		COND_MAXUPD_TMP CT 
	WHERE
		COND.PATID = CT.PATID 
		AND COND.PLURAL = CT.PLURAL 
		AND COND.CTL_NO = '006' 
		AND COND.UP_DATE = CT.MAX_UP_DATE 
	GROUP BY
		COND.PATID,
		COND.PLURAL,
		CT.MAX_UP_DATE 
	)
	,COND_VLAUE AS (
	SELECT
	COND.PATID,
	COND.PLURAL,
	COND.IND_NO,
	COND.UP_DATE,
	COND.VALUE_1W1N,
	COND.VALUE_1W2N,
	COND.VALUE_1W3N,
	COND.VALUE_1W4N,
	COND.VALUE_1W5N,
	COND.VALUE_1W6N,
	COND.VALUE_1W7N
FROM
	IND_DIALYSIS_COND COND
	INNER JOIN COND_TMP CT ON COND.PATID = CT.PATID 
	AND COND.PLURAL = CT.PLURAL 
	AND COND.CTL_NO = '006' 
	AND COND.IND_NO = CT.MAX_IND_NO 
	AND COND.UP_DATE = CT.MAX_UP_DATE 
	WHERE TO_CHAR( TO_DATE( :MST_DIFF_DATETIME, 'YYYY/MM/DD HH24:MI:SS' ), 'YYYYMMDD' ) <= COND.IND_END_DATE 
	)
	,SYS_TREAT_COND_SETTING_INFO AS (({0})),
TREAT_ITEM_CD_INFO AS (
	SELECT
		PATID,
		PLURAL 
	FROM
		SYS_TREAT_COND_SETTING_INFO STCS
		INNER JOIN COND_VLAUE IDC ON IDC.VALUE_1W1N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W2N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W3N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W4N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W5N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W6N = STCS.TREAT_ITEM_CD 
		OR IDC.VALUE_1W7N = STCS.TREAT_ITEM_CD 
	) SELECT DISTINCT
	TICI.PATID 
FROM
	TREAT_ITEM_CD_INFO TICI