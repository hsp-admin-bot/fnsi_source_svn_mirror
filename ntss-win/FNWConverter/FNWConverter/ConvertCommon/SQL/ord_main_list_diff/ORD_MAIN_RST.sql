WITH  CONVERT_HISTORY AS {0}
,DIALYSIS_LIST AS (
	SELECT  DIALYSIS_NO,PATID FROM  RST_DIALYSIS RD  CROSS
	JOIN CONVERT_HISTORY CH  WHERE    RD.START_DATE >=CH.START_DATE AND  RD.START_DATE <= CH.END_DATE
	)
SELECT PATID FROM (
SELECT
     RD.PATID
FROM
    RST_DIALYSIS_COND  B
	INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
    CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
	 RD.PATID
FROM
	RST_DIALYSIS_MEDICATION B
	INNER JOIN DIALYSIS_LIST RD ON B.DIALYSIS_NO = RD.DIALYSIS_NO
    CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID 
FROM
    RST_DIALYSIS_EQUIP B
    INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID 
FROM
    RST_DIALYSIS_ADDITION B 
    INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
     B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID
FROM
    DIALYSIS_LIST RD
    , RST_DIALYSIS_TREATMENT B 
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    RD.DIALYSIS_NO = B.DIALYSIS_NO 
	AND B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID 
FROM
    DIALYSIS_LIST RD
    , RST_DIALYSIS_COMPLAINT B 
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    RD.DIALYSIS_NO = B.DIALYSIS_NO 
	AND B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID
FROM
    DIALYSIS_LIST RD
    , RST_DIALYSIS_TREAT_PERSON B 
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    RD.DIALYSIS_NO = B.DIALYSIS_NO 
	AND B.UP_DATE > CH.CONVERT_DATETIME  GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID
FROM
    RST_RECEIPT_MEMO B 
    INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO=RD.DIALYSIS_NO
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.DIVISION = 1 
    AND B.ADD_FLG = 1 
	AND B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
	SELECT
		 RD.PATID
    FROM
		RST_DIALYSIS_TARE B
		INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
		CROSS JOIN CONVERT_HISTORY  CH
	WHERE
		B.ORDER_CLASS = '0' 
	AND B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
 SELECT
		 RD.PATID
	FROM
		RST_DIALYSIS_TARE B
		INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
		CROSS JOIN CONVERT_HISTORY  CH
	WHERE
		B.ORDER_CLASS = '1'
	AND B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
		 RD.PATID
	FROM
		RST_DIALYSIS_WATER_REMOVE B
		INNER JOIN DIALYSIS_LIST RD  ON B.DIALYSIS_NO = RD.DIALYSIS_NO
		CROSS JOIN CONVERT_HISTORY  CH
    WHERE
        B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID
UNION ALL
SELECT
     RD.PATID
FROM
    RST_DIALYSIS_DEVICE  B
	INNER JOIN DIALYSIS_LIST RD ON B.DIALYSIS_NO = RD.DIALYSIS_NO
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.UP_DATE > CH.CONVERT_DATETIME  GROUP BY RD.PATID
UNION ALL
SELECT
	 RD.PATID
FROM
	RST_DIALYSIS_DETAIL B
	INNER JOIN DIALYSIS_LIST RD ON B.DIALYSIS_NO = RD.DIALYSIS_NO
	CROSS JOIN CONVERT_HISTORY  CH
WHERE
    B.UP_DATE > CH.CONVERT_DATETIME GROUP BY RD.PATID ) A
GROUP BY PATID