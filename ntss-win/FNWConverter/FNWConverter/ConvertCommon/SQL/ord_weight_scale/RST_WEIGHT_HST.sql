WITH
	CONVERT_HISTORY AS ( SELECT * FROM SYNC_CONVERT_HISTORY A INNER JOIN SYNC_CONVERT_HISTORY_DTL B ON ( A.SEQ_NO = B.SEQ_NO ) WHERE TABLE_KIND = 'ORD' )
	,BED_TMP AS (
		SELECT
		BED_NO
		,BED_NAME
		,REG_DATE
		,NVL( LEAD ( REG_DATE, 1, NULL ) OVER ( PARTITION BY BED_NO ORDER BY BED_NO, REG_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_BED
	{SERIES_CD}
	) 
	,DEVICE_TMP AS (
		SELECT
		DEVICE_NO
		,DEVICE_NAME
		,UP_DATE
		,NVL( LEAD ( UP_DATE, 1, NULL ) OVER ( PARTITION BY DEVICE_NO ORDER BY DEVICE_NO, UP_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_DEVICE
	{SERIES_CD}
	) 
	,TREAT_ITEM_TMP AS (
		SELECT
		TREAT_ITEM_CD
		,TREAT_ITEM_NAME
		,DEVICE_MODE
		,REG_DATE
		,NVL( LEAD ( REG_DATE, 1, NULL ) OVER ( PARTITION BY TREAT_ITEM_CD ORDER BY TREAT_ITEM_CD, REG_DATE ASC ), SYSDATE ) AS END_DATE 
	FROM MST_TREAT_ITEM
	) 
	,RST_WEIGHT_HST_ALL AS (
	{1}
	)
	
SELECT
	RD.WEIGHT_NO
	,'体重計'|| RD.WEIGHT_NO AS WEIGHT_NAME
	,RD.MEASURE_DATE
	,RD.PATID
	,CASE
		WHEN RD.WEIGHT_CLASS IN ('0','5','6','7','8') THEN 0
		WHEN RD.WEIGHT_CLASS = '1' THEN 1
		WHEN RD.WEIGHT_CLASS IN ('2','3','4') THEN 2
		END WEIGHT_CLASS
	,RD.BED_NO
	,BT.BED_NAME
	,C.KUR_CD
	,C.KUR_NAME
	,C.DEVICE_NO
	,DT.DEVICE_NAME
	,C.TREAT_ITEM_CD
	,TIT.TREAT_ITEM_NAME
	,TIT.DEVICE_MODE
	,CASE
		WHEN RD.WHEEL_CHAIR_FLG IN (0,1,2) THEN 0
		WHEN RD.WHEEL_CHAIR_FLG IN (3,4,5) THEN 2
		END AS WHEEL_CHAIR_FLG
	,CASE
		WHEN RD.WHEEL_CHAIR_FLG IN (1,2,3) THEN 1
		WHEN RD.WHEEL_CHAIR_FLG IN (4,5) THEN 2
		WHEN RD.WHEEL_CHAIR_FLG = 0 THEN 0
		WHEN RD.WHEEL_CHAIR_FLG = 9 THEN NULL
		END AS SCALE_MODE
	,RD.TARGET_WEIGHT
	,RD.MEASURE_WEIGHT
	,RD.WEIGHT_VALUE
	,RD.OFFWATER_AMT_LIMIT
	,RD.WHEEL_CHAIR_WEIGHT
	,NVL(RD.REVISE_OFFWATER1,0) AS REVISE_OFFWATER1
	,NVL(RD.REVISE_OFFWATER2,0) AS REVISE_OFFWATER2
	,NVL(RD.REVISE_OFFWATER3,0) AS REVISE_OFFWATER3
	,NVL(RD.REVISE_OFFWATER4,0) AS REVISE_OFFWATER4
	,NVL(RD.REVISE_OFFWATER5,0) AS REVISE_OFFWATER5
	,RD.REVISE_OFFWATER_NAME1
	,RD.REVISE_OFFWATER_NAME2
	,RD.REVISE_OFFWATER_NAME3
	,RD.REVISE_OFFWATER_NAME4
	,RD.REVISE_OFFWATER_NAME5
	,NVL(RD.REVISE_TARE1,0) AS  REVISE_TARE1
	,NVL(RD.REVISE_TARE2,0) AS  REVISE_TARE2
	,NVL(RD.REVISE_TARE3,0) AS  REVISE_TARE3
	,NVL(RD.REVISE_TARE4,0) AS  REVISE_TARE4
	,NVL(RD.REVISE_TARE5,0) AS  REVISE_TARE5
	,RD.REVISE_TARE_NAME1
	,RD.REVISE_TARE_NAME2
	,RD.REVISE_TARE_NAME3
	,RD.REVISE_TARE_NAME4
	,RD.REVISE_TARE_NAME5
	,C.DIALYSIS_NO
	,CASE
		WHEN WHEEL_CHAIR_CD = '-' THEN
		NULL ELSE WHEEL_CHAIR_CD 
	END WHEEL_CHAIR_CD
	,WHEEL_CHAIR_NAME
	,TRIM( MEASURE_STAFF_CD ) AS MEASURE_STAFF_CD
	,RD.UP_DATE
FROM RST_WEIGHT_HST_ALL RD
	
	LEFT JOIN RST_DIALYSIS C
		ON RD.PATID = C.PATID
		AND RD.MEASURE_DATE <= C.LEAVE_DATE
		AND RD.MEASURE_DATE >= C.ENTER_DATE
	LEFT JOIN BED_TMP BT
		ON RD.BED_NO = BT.BED_NO
		AND RD.MEASURE_DATE >= BT.REG_DATE
		AND RD.MEASURE_DATE <= BT.END_DATE
	LEFT JOIN DEVICE_TMP DT
		ON C.DEVICE_NO = DT.DEVICE_NO
		AND RD.MEASURE_DATE >= DT.UP_DATE
		AND RD.MEASURE_DATE <= DT.END_DATE
	LEFT JOIN TREAT_ITEM_TMP TIT
		ON C.TREAT_ITEM_CD = TIT.TREAT_ITEM_CD
		AND RD.MEASURE_DATE >= TIT.REG_DATE
		AND RD.MEASURE_DATE <= TIT.END_DATE
	{0}

ORDER BY
	WEIGHT_NO