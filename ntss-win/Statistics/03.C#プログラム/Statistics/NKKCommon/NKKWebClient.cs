using System;
using System.Net;

//----------------------------------------------------------------------------------------------------
//  名前空間:NKKWebClientLib
//----------------------------------------------------------------------------------------------------
namespace NKKWebClientLib
{
    //----------------------------------------------------------------------------------------------------
    //  NKKWebClientクラス
    //----------------------------------------------------------------------------------------------------
    public class NKKWebClient : System.Net.WebClient
    {
        //----------------------------------------------------------------------------------------------------
        /// <summary>
        /// CookieContainer参照/設定用プロパティ
        /// </summary>
        //----------------------------------------------------------------------------------------------------
        public CookieContainer Cookie
        {
            get { return (this.m_CookieContainer); }
            set { this.m_CookieContainer = value; }
        }
        //----------------------------------------------------------------------------------------------------

        //----------------------------------------------------------------------------------------------------
        /// <summary>
        /// 保持するCookieContainer
        /// </summary>
        //----------------------------------------------------------------------------------------------------
        protected CookieContainer m_CookieContainer = new CookieContainer();
        //----------------------------------------------------------------------------------------------------

        //----------------------------------------------------------------------------------------------------
        /// <summary>
        /// WebRequest処理のoverride
        /// </summary>
        /// <param name="address">URI</param>
        /// <returns></returns>
        //----------------------------------------------------------------------------------------------------
        protected override WebRequest GetWebRequest(Uri address )
        {
            WebRequest res = base.GetWebRequest(address);
            if( res is HttpWebRequest )
            {
                // CookieContainerを設定
                ((HttpWebRequest)res).CookieContainer = this.m_CookieContainer;
            }

            return res;
        }
        //----------------------------------------------------------------------------------------------------
    }
    //----------------------------------------------------------------------------------------------------
}
